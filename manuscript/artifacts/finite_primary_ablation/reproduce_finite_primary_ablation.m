function pathValue = resolveResultFile(storedPath, campaignRoot)
pathValue = string(storedPath);
normalized = replace(pathValue, "/", filesep);
marker = filesep + "runs" + filesep;
location = strfind(lower(normalized), lower(marker));
if ~isempty(location)
    suffix = extractAfter(normalized, ...
        location(end) + strlength(marker) - 1);
    rebasedPath = fullfile(campaignRoot, "runs", suffix);
    if isfile(rebasedPath)
        pathValue = rebasedPath;
        return
    end
end
if isfile(pathValue)
    return
end
error("cTSEMO:Comparison:CannotResolveResult", ...
    "Cannot resolve stored result path '%s' below %s.", ...
    storedPath, campaignRoot);
end

function assertEquivalentCoreOptions(oldOptions, newOptions, ...
        problemId, replicate)
assert(double(oldOptions.maxEvaluations) == ...
    double(newOptions.maxEvaluations), ...
    "Sequential budget option differs for %s replicate %d.", ...
    problemId, replicate);
assert(double(oldOptions.seed) == double(newOptions.seed), ...
    "Solver seed option differs for %s replicate %d.", ...
    problemId, replicate);
commonFields = ["feasibility", "candidates", "objectiveGP", "pof", ...
    "acquisition", "masks", "challengers", "fallback"];
for fieldIndex = 1:numel(commonFields)
    field = commonFields(fieldIndex);
    assert(isfield(oldOptions, field) && isfield(newOptions, field) && ...
        strcmp(jsonencode(oldOptions.(field)), ...
        jsonencode(newOptions.(field))), ...
        "Core option '%s' differs for %s replicate %d.", ...
        field, problemId, replicate);
end
oldMethod = "pool";
if isfield(oldOptions, "primarySearch") && ...
        isfield(oldOptions.primarySearch, "method")
    oldMethod = string(oldOptions.primarySearch.method);
end
assert(oldMethod == "pool", ...
    "Archived primary method is not finite-pool for %s replicate %d.", ...
    problemId, replicate);
assert(isfield(newOptions, "primarySearch") && ...
    isfield(newOptions.primarySearch, "method") && ...
    string(newOptions.primarySearch.method) == "ga", ...
    "Current primary method is not GA for %s replicate %d.", ...
    problemId, replicate);
end

function values = normalizeValues(values, lower, scale)
values = (double(values) - lower) ./ scale;
end

function history = fixedHypervolumeHistory( ...
        Y, labels, nInitial, lower, scale, referencePoint)
nSequential = size(Y, 1) - nInitial;
history = zeros(nSequential + 1, 1);
for step = 0:nSequential
    lastRow = nInitial + step;
    feasible = Y(1:lastRow, :);
    feasible = feasible(labels(1:lastRow), :);
    history(step + 1) = ctsemo.hypervolume2d( ...
        normalizeValues(feasible, lower, scale), referencePoint);
end
end

function [aOverB, bOverA] = bidirectionalCoverage(A, B, tolerance)
aOverB = strictCoverage(A, B, tolerance);
bOverA = strictCoverage(B, A, tolerance);
end

function percentage = strictCoverage(A, B, tolerance)
if isempty(B)
    percentage = NaN;
    return
end
dominated = false(size(B, 1), 1);
for pointIndex = 1:size(B, 1)
    target = B(pointIndex, :);
    dominated(pointIndex) = any( ...
        all(A <= target + tolerance, 2) & ...
        any(A < target - tolerance, 2));
end
percentage = 100 .* mean(dominated);
end

function timing = extractTiming(result)
timing = struct("wall", double(result.meta.wallTimeSeconds), ...
    "acquisition", NaN);
if ~isempty(result.iterations) && ...
        isfield(result.iterations, "timing")
    values = arrayfun(@(record) ...
        double(record.timing.acquisitionSeconds), result.iterations);
    timing.acquisition = mean(values);
end
end

function diagnostics = extractGaDiagnostics(result)
diagnostics = struct("eligible", 0, "improved", 0, ...
    "returnedSeedBest", 0, "meanImprovement", NaN);
improvements = zeros(0, 1);
for iterationIndex = 1:numel(result.iterations)
    record = result.iterations(iterationIndex);
    if ~isfield(record, "primarySearch") || ...
            ~isstruct(record.primarySearch)
        continue
    end
    search = record.primarySearch;
    if ~isfield(search, "method") || ~isfield(search, "status") || ...
            string(search.method) ~= "ga" || ...
            string(search.status) ~= "completed" || ...
            ~isfield(search, "improvementOverSeed") || ...
            isempty(search.improvementOverSeed) || ...
            ~isscalar(search.improvementOverSeed) || ...
            ~isfinite(double(search.improvementOverSeed))
        continue
    end
    improvement = double(search.improvementOverSeed);
    diagnostics.eligible = diagnostics.eligible + 1;
    diagnostics.improved = diagnostics.improved + (improvement > 1e-12);
    improvements(end + 1, 1) = improvement; %#ok<AGROW>
    if isfield(search, "returnedSeedBest") && ...
            isscalar(search.returnedSeedBest)
        diagnostics.returnedSeedBest = diagnostics.returnedSeedBest + ...
            logical(search.returnedSeedBest);
    end
end
if ~isempty(improvements)
    diagnostics.meanImprovement = mean(improvements);
end
end

function assessment = classifyResult( ...
        changePct, aucDelta, wins, losses, zeroBaselineGains)
if zeroBaselineGains > 0 && wins >= 4 && losses == 0 && aucDelta >= 0
    assessment = "directional improvement with zero-baseline cases";
elseif zeroBaselineGains > 0
    assessment = "mixed; includes zero-baseline gains";
elseif isfinite(changePct) && changePct >= 5 && wins >= 4 && aucDelta >= 0
    assessment = "strong improvement";
elseif isfinite(changePct) && changePct >= 2 && wins >= 4 && aucDelta >= 0
    assessment = "practical improvement";
elseif isfinite(changePct) && changePct <= -5 && losses >= 4
    assessment = "material regression";
elseif isfinite(changePct) && changePct <= -2 && losses >= 4
    assessment = "regression concern";
elseif isfinite(changePct) && abs(changePct) < 2
    assessment = "effectively tied";
else
    assessment = "mixed";
end
end

function interaction = makeDimensionInteractions(paired, tolerance)
families = ["CF1"; "C2DTLZ2"; "MW7"];
lowIds = ["CF1_D4"; "C2DTLZ2_D4_R02"; "MW7_D4"];
highIds = ["CF1_D10"; "C2DTLZ2_D6_R02"; "MW7_D6"];
rows = repmat(struct("Family", "", "Replicate", NaN, ...
    "LowDimension", NaN, "HighDimension", NaN, ...
    "LowDimensionRelativeHVChangePct", NaN, ...
    "HighDimensionRelativeHVChangePct", NaN, ...
    "InteractionPctPoints", NaN), 0, 1);
for familyIndex = 1:numel(families)
    low = sortrows(paired(paired.ProblemId == lowIds(familyIndex), :), ...
        "Replicate");
    high = sortrows(paired(paired.ProblemId == highIds(familyIndex), :), ...
        "Replicate");
    assert(isequal(low.Replicate, high.Replicate), ...
        "Dimension-pair replicate identities differ for %s.", ...
        families(familyIndex));
    for replicateIndex = 1:height(low)
        lowRelative = relativeChange( ...
            low.OldFinalHV(replicateIndex), ...
            low.NewFinalHV(replicateIndex), tolerance);
        highRelative = relativeChange( ...
            high.OldFinalHV(replicateIndex), ...
            high.NewFinalHV(replicateIndex), tolerance);
        row = struct("Family", families(familyIndex), ...
            "Replicate", low.Replicate(replicateIndex), ...
            "LowDimension", low.Dimension(replicateIndex), ...
            "HighDimension", high.Dimension(replicateIndex), ...
            "LowDimensionRelativeHVChangePct", lowRelative, ...
            "HighDimensionRelativeHVChangePct", highRelative, ...
            "InteractionPctPoints", highRelative - lowRelative);
        rows(end + 1, 1) = row; %#ok<AGROW>
    end
end
interaction = struct2table(rows);
end

function value = relativeChange(oldValue, newValue, tolerance)
value = NaN;
if oldValue > tolerance
    value = 100 .* (newValue - oldValue) ./ oldValue;
elseif oldValue <= tolerance && newValue <= tolerance
    value = 0;
end
end

function plotHypervolumeChanges(paired, problemIds, outputRoot)
figureHandle = figure("Visible", "off", "Color", "w", ...
    "Position", [100, 100, 1450, 800]);
