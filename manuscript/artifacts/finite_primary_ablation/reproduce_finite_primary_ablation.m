function assertTablesEquivalent(actual, expected, tolerance)
assert(isequal(actual.Properties.VariableNames, ...
    expected.Properties.VariableNames) && height(actual) == height(expected), ...
    "Recomputed ablation table schema differs from the retained authority.");
for variable = string(actual.Properties.VariableNames)
    a = actual.(variable);
    b = expected.(variable);
    if isnumeric(a) || islogical(a)
        a = double(a);
        b = double(b);
        equal = (isnan(a) & isnan(b)) | abs(a - b) <= tolerance;
        assert(all(equal, "all"), ...
            "Recomputed values differ for column %s.", variable);
    else
        assert(isequal(string(a), string(b)), ...
            "Recomputed text differs for column %s.", variable);
    end
end
end

function result = compactFiniteResult(evaluations, summaryRow, coreOptions)
problemId = string(summaryRow.ProblemId);
replicate = double(summaryRow.Replicate);
rows = evaluations(evaluations.ProblemId == problemId & ...
    evaluations.Replicate == replicate, :);
rows = sortrows(rows, "EvaluationIndex");
assert(height(rows) == double(summaryRow.TotalEvaluations), ...
    "Finite-primary row count differs for %s replicate %d.", ...
    problemId, replicate);
dimension = double(summaryRow.Dimension);
inputNames = "X" + string(1:dimension);
result = struct();
result.meta = struct("wallTimeSeconds", double(summaryRow.WallTimeSeconds));
result.data = struct( ...
    "X", table2array(rows(:, inputNames)), ...
    "Y", [rows.Objective1, rows.Objective2], ...
    "constraintValues", rows.ConstraintValue, ...
    "isFeasible", logical(rows.IsFeasible), ...
    "nInitial", double(summaryRow.InitialCount));

sequential = rows(~logical(rows.IsInitial), :);
iterationTemplate = struct( ...
    "selectionSource", "", ...
    "timing", struct("acquisitionSeconds", NaN));
result.iterations = repmat(iterationTemplate, height(sequential), 1);
for index = 1:height(sequential)
    result.iterations(index).selectionSource = ...
        string(sequential.SelectionSource(index));
    result.iterations(index).timing.acquisitionSeconds = ...
        double(sequential.AcquisitionSeconds(index));
end
result.options = coreOptions;
if isfield(result.options, "primarySearchMethod")
    result.options = rmfield(result.options, "primarySearchMethod");
end
result.options.seed = double(summaryRow.SolverSeed);
result.options.primarySearch = struct("method", "pool");
end

