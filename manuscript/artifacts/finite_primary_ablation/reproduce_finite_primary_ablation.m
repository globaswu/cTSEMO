% Matched comparison of the current GA-primary and archived finite-pool runs.
% The old optimizer is not rerun. All quality metrics are recomputed from
% evaluated feasible observations under one pooled normalization and fixed
% reference point per problem.

artifactRoot = string(fileparts(mfilename("fullpath")));
repo = string(fileparts(fileparts(fileparts(artifactRoot))));
newRoot = fullfile(repo, "manuscript", "artifacts", ...
    "ga_primary_dimension");
outputRoot = fullfile(repo, "generated", "finite_primary_ablation");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end
normalizationFile = fullfile(artifactRoot, ...
    "comparison_normalization_reference.csv");
normalizationReference = readtable(normalizationFile, "TextType", "string");
addpath(fullfile(repo, "src"));
addpath(fullfile(repo, "src", "benchmarks"));

oldSummary = readtable(fullfile(artifactRoot, ...
    "finite_primary_run_summary.csv"), ...
    "TextType", "string");
oldEvaluations = readtable(fullfile(artifactRoot, ...
    "finite_primary_evaluations.csv"), ...
    "TextType", "string", VariableNamingRule="preserve");
oldCoreOptions = jsondecode(fileread(fullfile(artifactRoot, ...
    "finite_primary_core_options.json")));
newSummary = readtable(fullfile(newRoot, "run_summary.csv"), ...
    "TextType", "string");
problemIds = ["WELDEDBEAM"; "CF1_D4"; "CF1_D10"; ...
    "C2DTLZ2_D4_R02"; "C2DTLZ2_D6_R02"; "MW7_D4"; "MW7_D6"];
referencePoint = [1.1, 1.1];
comparisonTolerance = 1e-10;

assert(height(oldSummary) == 35 && height(newSummary) == 35, ...
    "Expected 35 archived and 35 current trajectories.");
assert(all(oldSummary.Status == "completed") && ...
    all(newSummary.Status == "completed"), ...
    "Every trajectory must be completed before comparison.");

pairedRows = repmat(emptyPairedRow(), 0, 1);
problemLower = cell(numel(problemIds), 1);
problemScale = cell(numel(problemIds), 1);
normalizationRows = repmat(struct( ...
    "ProblemId", "", "Lower1", NaN, "Lower2", NaN, ...
    "Scale1", NaN, "Scale2", NaN, ...
    "Reference1", referencePoint(1), ...
    "Reference2", referencePoint(2)), numel(problemIds), 1);

for problemIndex = 1:numel(problemIds)
    problemId = problemIds(problemIndex);
    oldRows = sortrows(oldSummary(oldSummary.ProblemId == problemId, :), ...
        "Replicate");
    newRows = sortrows(newSummary(newSummary.ProblemId == problemId, :), ...
        "Replicate");
    assert(height(oldRows) == 5 && height(newRows) == 5, ...
        "Expected five matched replicates for %s.", problemId);
    assert(isequal(oldRows.Replicate, newRows.Replicate) && ...
        isequal(oldRows.InitialSeed, newRows.InitialSeed) && ...
        isequal(oldRows.SolverSeed, newRows.SolverSeed), ...
        "Replicate or seed pairing differs for %s.", problemId);

    pooledFeasibleParts = cell(10, 1);
    for replicateIndex = 1:5
        newFile = resolveResultFile( ...
            newRows.ResultFile(replicateIndex), newRoot);
        newLoaded = load(newFile, "result");
        oldResult = compactFiniteResult(oldEvaluations, ...
            oldRows(replicateIndex, :), oldCoreOptions);
        newResult = newLoaded.result;
        pooledFeasibleParts{2 .* replicateIndex - 1} = ...
            oldResult.data.Y(logical(oldResult.data.isFeasible), :);
        pooledFeasibleParts{2 .* replicateIndex} = ...
            newResult.data.Y(logical(newResult.data.isFeasible), :);
    end
    pooledFeasible = vertcat(pooledFeasibleParts{:});
    assert(~isempty(pooledFeasible), ...
        "No feasible objective observations exist for %s.", problemId);
    storedReference = normalizationReference( ...
        normalizationReference.ProblemId == problemId, :);
    assert(height(storedReference) == 1, ...
        "Normalization reference is missing or duplicated for %s.", problemId);
    lower = [storedReference.Lower1, storedReference.Lower2];
    scale = [storedReference.Scale1, storedReference.Scale2];
    problemLower{problemIndex} = lower;
    problemScale{problemIndex} = scale;
    normalizationRows(problemIndex, 1) = struct( ...
        "ProblemId", problemId, ...
        "Lower1", lower(1), "Lower2", lower(2), ...
        "Scale1", scale(1), "Scale2", scale(2), ...
        "Reference1", referencePoint(1), ...
        "Reference2", referencePoint(2));

    for replicateIndex = 1:5
        newFile = resolveResultFile( ...
            newRows.ResultFile(replicateIndex), newRoot);
        newLoaded = load(newFile, "result");
        oldResult = compactFiniteResult(oldEvaluations, ...
            oldRows(replicateIndex, :), oldCoreOptions);
        newResult = newLoaded.result;

        nInitial = double(oldResult.data.nInitial);
        assert(double(newResult.data.nInitial) == nInitial, ...
            "Initial count differs for %s replicate %d.", ...
            problemId, replicateIndex);
        assert(size(oldResult.data.Y, 1) == size(newResult.data.Y, 1), ...
            "Evaluation count differs for %s replicate %d.", ...
            problemId, replicateIndex);
        initialRows = 1:nInitial;
        assert(max(abs(oldResult.data.X(initialRows, :) - ...
            newResult.data.X(initialRows, :)), [], "all") < 1e-10, ...
            "Initial X differs for %s replicate %d.", ...
            problemId, replicateIndex);
        assert(max(abs(oldResult.data.Y(initialRows, :) - ...
            newResult.data.Y(initialRows, :)), [], "all") < 1e-10, ...
            "Initial Y differs for %s replicate %d.", ...
            problemId, replicateIndex);
        assert(isequal(logical(oldResult.data.isFeasible(initialRows)), ...
            logical(newResult.data.isFeasible(initialRows))), ...
            "Initial labels differ for %s replicate %d.", ...
            problemId, replicateIndex);
        assertEquivalentCoreOptions( ...
            oldResult.options, newResult.options, problemId, replicateIndex);

        oldLabels = logical(oldResult.data.isFeasible);
        newLabels = logical(newResult.data.isFeasible);
        oldFront = ctsemo.pareto2d(oldResult.data.Y(oldLabels, :));
        newFront = ctsemo.pareto2d(newResult.data.Y(newLabels, :));
        oldFrontNormalized = normalizeValues(oldFront, lower, scale);
        newFrontNormalized = normalizeValues(newFront, lower, scale);
        oldFeasibleNormalized = normalizeValues( ...
            oldResult.data.Y(oldLabels, :), lower, scale);
        newFeasibleNormalized = normalizeValues( ...
            newResult.data.Y(newLabels, :), lower, scale);
        assert(all(oldFeasibleNormalized < referencePoint, "all") && ...
            all(newFeasibleNormalized < referencePoint, "all"), ...
            "Fixed reference does not dominate all observations for " + ...
            "%s replicate %d.", problemId, replicateIndex);

        oldHistory = fixedHypervolumeHistory( ...
            oldResult.data.Y, oldLabels, nInitial, lower, scale, ...
            referencePoint);
        newHistory = fixedHypervolumeHistory( ...
            newResult.data.Y, newLabels, nInitial, lower, scale, ...
            referencePoint);
        initialHV = oldHistory(1);
        assert(abs(initialHV - newHistory(1)) < 1e-12, ...
            "Initial hypervolume differs for %s replicate %d.", ...
            problemId, replicateIndex);
        oldFinalHV = oldHistory(end);
        newFinalHV = newHistory(end);
        oldAUC = trapz(0:(numel(oldHistory) - 1), oldHistory) ./ ...
            max(1, numel(oldHistory) - 1);
        newAUC = trapz(0:(numel(newHistory) - 1), newHistory) ./ ...
            max(1, numel(newHistory) - 1);

        [newOverOld, oldOverNew] = bidirectionalCoverage( ...
            newFrontNormalized, oldFrontNormalized, comparisonTolerance);
        oldTiming = extractTiming(oldResult);
        newTiming = extractTiming(newResult);
        newSources = reshape(string( ...
            {newResult.iterations.selectionSource}), [], 1);
        ga = extractGaDiagnostics(newResult);

        row = emptyPairedRow();
        row.ProblemId = problemId;
        row.Dimension = size(oldResult.data.X, 2);
        row.Replicate = double(oldRows.Replicate(replicateIndex));
        row.InitialCount = nInitial;
        row.TotalEvaluations = size(oldResult.data.Y, 1);
        row.OldFeasibleCount = nnz(oldLabels);
        row.NewFeasibleCount = nnz(newLabels);
        row.OldUniqueFrontCount = size(oldFront, 1);
        row.NewUniqueFrontCount = size(newFront, 1);
        row.InitialHV = initialHV;
        row.OldFinalHV = oldFinalHV;
        row.NewFinalHV = newFinalHV;
        row.FinalHVDelta = newFinalHV - oldFinalHV;
        row.FinalHVChangePct = relativeChange( ...
            oldFinalHV, newFinalHV, comparisonTolerance);
        row.ZeroBaselineHVGain = ...
            oldFinalHV <= comparisonTolerance && ...
            newFinalHV > comparisonTolerance;
        row.OldHVGrowth = oldFinalHV - initialHV;
        row.NewHVGrowth = newFinalHV - initialHV;
        row.OldHVAUC = oldAUC;
        row.NewHVAUC = newAUC;
        row.HVAUCDelta = newAUC - oldAUC;
        row.HVAUCChangePct = relativeChange( ...
            oldAUC, newAUC, comparisonTolerance);
        row.ZeroBaselineHVAUCGain = ...
            all(oldAUC <= comparisonTolerance, "all") && ...
            all(newAUC > comparisonTolerance, "all");
        row.NewStrictlyDominatesOldPct = newOverOld;
        row.OldStrictlyDominatesNewPct = oldOverNew;
        row.OldWallTimeSeconds = oldTiming.wall;
        row.NewWallTimeSeconds = newTiming.wall;
        row.OldMeanAcquisitionSeconds = oldTiming.acquisition;
        row.NewMeanAcquisitionSeconds = newTiming.acquisition;
        row.NewPrimarySelections = nnz(newSources == "primary");
        row.NewChallengerSelections = nnz(newSources == "challenger");
        row.NewFallbackSelections = nnz(newSources == "fallback");
        row.GAEligibleIterations = ga.eligible;
        row.GAImprovedOverSeedCount = ga.improved;
        row.GAReturnedSeedBestCount = ga.returnedSeedBest;
        row.GAMeanImprovementOverSeed = ga.meanImprovement;
        pairedRows(end + 1, 1) = row; %#ok<SAGROW>
    end
end

paired = struct2table(pairedRows);
expectedPaired = readtable(fullfile(artifactRoot, ...
