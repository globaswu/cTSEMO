for problemIndex = 1:numel(problemIds)
    problemId = problemIds(problemIndex);
    subset = paired(paired.ProblemId == problemId, :);
    delta = subset.FinalHVDelta;
    oldMedian = median(subset.OldFinalHV);
    newMedian = median(subset.NewFinalHV);
    pairedChangePct = median( ...
        subset.FinalHVChangePct, "omitmissing");
    aucOldMedian = median(subset.OldHVAUC);
    aucNewMedian = median(subset.NewHVAUC);
    pairedAUCChangePct = median( ...
        subset.HVAUCChangePct, "omitmissing");
    wins = nnz(delta > comparisonTolerance);
    losses = nnz(delta < -comparisonTolerance);
    ties = height(subset) - wins - losses;

    row = emptyAggregateRow();
    row.ProblemId = problemId;
    row.Dimension = subset.Dimension(1);
    row.Replicates = height(subset);
    row.OldMedianFinalHV = oldMedian;
    row.NewMedianFinalHV = newMedian;
    row.MedianPairedHVDelta = median(delta);
    row.MedianPairedHVChangePct = pairedChangePct;
    row.HVWins = wins;
    row.HVTies = ties;
    row.HVLosses = losses;
    row.OldMedianHVAUC = aucOldMedian;
    row.NewMedianHVAUC = aucNewMedian;
    row.MedianPairedHVAUCDelta = median(subset.HVAUCDelta);
    row.MedianPairedHVAUCChangePct = pairedAUCChangePct;
    row.ZeroBaselineHVGainCount = nnz(subset.ZeroBaselineHVGain);
    row.ZeroBaselineHVAUCGainCount = nnz(subset.ZeroBaselineHVAUCGain);
    row.MedianNewStrictlyDominatesOldPct = ...
        median(subset.NewStrictlyDominatesOldPct, "omitmissing");
    row.MedianOldStrictlyDominatesNewPct = ...
        median(subset.OldStrictlyDominatesNewPct, "omitmissing");
    row.OldMedianFeasibleCount = median(subset.OldFeasibleCount);
    row.NewMedianFeasibleCount = median(subset.NewFeasibleCount);
    row.ChallengerOverrideRate = sum(subset.NewChallengerSelections) ./ ...
        max(1, sum(subset.NewPrimarySelections + ...
        subset.NewChallengerSelections));
    row.FallbackRate = sum(subset.NewFallbackSelections) ./ ...
        sum(subset.TotalEvaluations - subset.InitialCount);
    row.GAImprovedOverSeedRate = sum(subset.GAImprovedOverSeedCount) ./ ...
        max(1, sum(subset.GAEligibleIterations));
    row.MedianAcquisitionTimeRatio = median( ...
        subset.NewMeanAcquisitionSeconds ./ ...
        subset.OldMeanAcquisitionSeconds);
    row.Assessment = classifyResult( ...
        pairedChangePct, median(subset.HVAUCDelta), wins, losses, ...
        row.ZeroBaselineHVGainCount);
    aggregateRows(end + 1, 1) = row; %#ok<SAGROW>
end

