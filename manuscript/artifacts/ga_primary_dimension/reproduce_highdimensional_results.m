% Reproduce summaries and figures from the retained GA-primary trajectories.
% No finite-pool trajectory or omitted dense probe array is loaded.

studyRoot = string(fileparts(mfilename("fullpath")));
repoRoot = string(fileparts(fileparts(fileparts(studyRoot))));
addpath(fullfile(repoRoot, "src"));
addpath(fullfile(repoRoot, "src", "benchmarks"));

runs = readtable(fullfile(studyRoot, "run_summary.csv"), ...
    "TextType", "string");
normalization = readtable(fullfile(studyRoot, ...
    "ga_primary_highdim_normalization.csv"), "TextType", "string");
problemIds = ["WELDEDBEAM"; "CF1_D4"; "CF1_D10"; ...
    "C2DTLZ2_D4_R02"; "C2DTLZ2_D6_R02"; "MW7_D4"; "MW7_D6"];
displayNames = ["Welded beam D4"; "CF1 D4"; "CF1 D10"; ...
    "C2-DTLZ2 D4"; "C2-DTLZ2 D6"; "MW7 D4"; "MW7 D6"];
assert(height(runs) == 35 && all(runs.Status == "completed"), ...
    "Expected 35 completed GA-primary trajectories.");

perRunRows = repmat(emptyPerRunRow(), 0, 1);
historyByProblem = cell(numel(problemIds), 1);
frontByProblem = cell(numel(problemIds), 1);

for problemIndex = 1:numel(problemIds)
    problemId = problemIds(problemIndex);
    problemRows = sortrows(runs(runs.ProblemId == problemId, :), ...
        "Replicate");
    assert(height(problemRows) == 5, ...
        "Expected five trajectories for %s.", problemId);

    results = cell(5, 1);
    for replicateIndex = 1:5
        resultFile = resolveResultFile( ...
            problemRows.ResultFile(replicateIndex), studyRoot);
        loaded = load(resultFile, "result");
        results{replicateIndex} = loaded.result;
    end

    normalizationRow = normalization( ...
        normalization.ProblemId == problemId, :);
    assert(height(normalizationRow) == 1, ...
        "Expected one normalization row for %s.", problemId);
    lower = [normalizationRow.Lower1, normalizationRow.Lower2];
    scale = [normalizationRow.Scale1, normalizationRow.Scale2];
    referencePoint = [ ...
        normalizationRow.Reference1, normalizationRow.Reference2];

    histories = NaN(131, 5);
    fronts = cell(5, 1);
    for replicateIndex = 1:5
        result = results{replicateIndex};
        labels = logical(result.data.isFeasible);
        nInitial = double(result.data.nInitial);
        assert(nInitial == 20 && size(result.data.Y, 1) == 150, ...
            "Unexpected evaluation budget for %s replicate %d.", ...
            problemId, replicateIndex);
        history = fixedHypervolumeHistory( ...
            result.data.Y, labels, nInitial, lower, scale, ...
            referencePoint);
        histories(:, replicateIndex) = history;
        front = ctsemo.pareto2d(result.data.Y(labels, :));
        fronts{replicateIndex} = normalizeValues(front, lower, scale);
        sources = reshape(string( ...
            {result.iterations.selectionSource}), [], 1);
        primaryCount = nnz(sources == "primary");
        challengerCount = nnz(sources == "challenger");
        fallbackCount = nnz(sources == "fallback");
        ordinaryCount = primaryCount + challengerCount;
        ga = extractGaDiagnostics(result);

        row = emptyPerRunRow();
        row.ProblemId = problemId;
        row.Dimension = size(result.data.X, 2);
        row.Replicate = replicateIndex;
        row.FinalFeasibleCount = nnz(labels);
        row.FinalParetoCount = size(front, 1);
        row.FinalNormalizedHV = history(end);
        row.NormalizedHVAUC = trapz(0:130, history) ./ 130;
        row.PrimarySelections = primaryCount;
        row.ChallengerSelections = challengerCount;
        row.FallbackSelections = fallbackCount;
        row.ChallengerOverrideRate = challengerCount ./ max(1, ordinaryCount);
        row.FallbackRate = fallbackCount ./ 130;
        row.MeanAcquisitionSeconds = ...
            double(problemRows.MeanAcquisitionSeconds(replicateIndex));
        row.WallTimeSeconds = ...
            double(problemRows.WallTimeSeconds(replicateIndex));
        row.GAEligibleIterations = ga.eligible;
        row.GAImprovedOverSeedCount = ga.improved;
        perRunRows(end + 1, 1) = row; %#ok<SAGROW>
    end
    historyByProblem{problemIndex} = histories;
    frontByProblem{problemIndex} = fronts;
end

perRun = struct2table(perRunRows);
summaryRows = repmat(emptySummaryRow(), numel(problemIds), 1);
for problemIndex = 1:numel(problemIds)
    subset = perRun(perRun.ProblemId == problemIds(problemIndex), :);
    totalPrimary = sum(subset.PrimarySelections);
    totalChallenger = sum(subset.ChallengerSelections);
    totalFallback = sum(subset.FallbackSelections);
    ordinary = totalPrimary + totalChallenger;
    summaryRows(problemIndex) = struct( ...
        "ProblemId", problemIds(problemIndex), ...
        "Dimension", subset.Dimension(1), ...
        "Replicates", height(subset), ...
        "MedianFinalFeasibleCount", median(subset.FinalFeasibleCount), ...
        "MinimumFinalFeasibleCount", min(subset.FinalFeasibleCount), ...
        "MaximumFinalFeasibleCount", max(subset.FinalFeasibleCount), ...
        "MedianFinalParetoCount", median(subset.FinalParetoCount), ...
        "MinimumFinalParetoCount", min(subset.FinalParetoCount), ...
        "MaximumFinalParetoCount", max(subset.FinalParetoCount), ...
        "MedianFinalNormalizedHV", median(subset.FinalNormalizedHV), ...
        "MedianNormalizedHVAUC", median(subset.NormalizedHVAUC), ...
        "PrimarySelectionCount", totalPrimary, ...
        "ChallengerSelectionCount", totalChallenger, ...
        "FallbackSelectionCount", totalFallback, ...
        "ChallengerOverrideRate", totalChallenger ./ max(1, ordinary), ...
        "FallbackRate", totalFallback ./ (height(subset) .* 130), ...
        "MedianMeanAcquisitionSeconds", ...
            median(subset.MeanAcquisitionSeconds), ...
        "MedianWallTimeSeconds", median(subset.WallTimeSeconds), ...
        "GAImprovedOverSeedRate", ...
            sum(subset.GAImprovedOverSeedCount) ./ ...
            max(1, sum(subset.GAEligibleIterations)));
end
summary = struct2table(summaryRows);

writetable(perRun, fullfile(studyRoot, ...
    "ga_primary_highdim_per_run.csv"));
writetable(summary, fullfile(studyRoot, ...
    "ga_primary_highdim_summary.csv"));
plotHypervolumeHistories( ...
    historyByProblem, displayNames, studyRoot);
plotSelectionSources(summary, displayNames, studyRoot);
plotFinalFronts(frontByProblem, displayNames, studyRoot);

disp(summary(:, ["ProblemId", "Dimension", ...
    "MedianFinalFeasibleCount", "MedianFinalParetoCount", ...
    "MedianFinalNormalizedHV", "ChallengerOverrideRate", ...
    "FallbackRate", "MedianMeanAcquisitionSeconds", ...
    "GAImprovedOverSeedRate"]));

function row = emptyPerRunRow()
row = struct( ...
    "ProblemId", "", "Dimension", NaN, "Replicate", NaN, ...
    "FinalFeasibleCount", NaN, "FinalParetoCount", NaN, ...
    "FinalNormalizedHV", NaN, "NormalizedHVAUC", NaN, ...
    "PrimarySelections", NaN, "ChallengerSelections", NaN, ...
    "FallbackSelections", NaN, "ChallengerOverrideRate", NaN, ...
    "FallbackRate", NaN, "MeanAcquisitionSeconds", NaN, ...
    "WallTimeSeconds", NaN, "GAEligibleIterations", NaN, ...
    "GAImprovedOverSeedCount", NaN);
end

function row = emptySummaryRow()
row = struct( ...
    "ProblemId", "", "Dimension", NaN, "Replicates", NaN, ...
    "MedianFinalFeasibleCount", NaN, ...
    "MinimumFinalFeasibleCount", NaN, ...
    "MaximumFinalFeasibleCount", NaN, ...
    "MedianFinalParetoCount", NaN, ...
    "MinimumFinalParetoCount", NaN, ...
    "MaximumFinalParetoCount", NaN, ...
    "MedianFinalNormalizedHV", NaN, ...
    "MedianNormalizedHVAUC", NaN, ...
    "PrimarySelectionCount", NaN, ...
    "ChallengerSelectionCount", NaN, ...
    "FallbackSelectionCount", NaN, ...
    "ChallengerOverrideRate", NaN, "FallbackRate", NaN, ...
    "MedianMeanAcquisitionSeconds", NaN, ...
    "MedianWallTimeSeconds", NaN, ...
    "GAImprovedOverSeedRate", NaN);
end

function pathValue = resolveResultFile(storedPath, campaignRoot)
pathValue = string(storedPath);
normalized = replace(pathValue, "/", filesep);
marker = filesep + "runs" + filesep;
location = strfind(lower(normalized), lower(marker));
if ~isempty(location)
    suffix = extractAfter(normalized, ...
        location(end) + strlength(marker) - 1);
    pathParts = split(suffix, filesep);
    rebasedPath = fullfile(campaignRoot, "runs", ...
        pathParts(1), "result.mat");
    if isfile(rebasedPath)
        pathValue = rebasedPath;
        return
    end
end
if isfile(pathValue)
    return
end
error("cTSEMO:GaSummary:CannotResolveResult", ...
    "Cannot resolve stored result path '%s' below %s.", ...
    storedPath, campaignRoot);
end

function values = normalizeValues(values, lower, scale)
values = (double(values) - lower) ./ scale;
end

function history = fixedHypervolumeHistory( ...
        Y, labels, nInitial, lower, scale, referencePoint)
nSequential = size(Y, 1) - nInitial;
history = zeros(nSequential + 1, 1);
for step = 0:nSequential
    lastRow = nInitial + step;
    feasible = Y(1:lastRow, :);
    feasible = feasible(labels(1:lastRow), :);
    normalized = normalizeValues(feasible, lower, scale);
    assert(isempty(normalized) || ...
        all(normalized < referencePoint, "all"), ...
        "The fixed reference does not dominate a feasible observation.");
    history(step + 1) = ...
        ctsemo.hypervolume2d(normalized, referencePoint);
end
end

function diagnostics = extractGaDiagnostics(result)
diagnostics = struct("eligible", 0, "improved", 0);
for iterationIndex = 1:numel(result.iterations)
    if ~isfield(result.iterations(iterationIndex), "primarySearch")
        continue
    end
    search = result.iterations(iterationIndex).primarySearch;
    if ~isstruct(search) || ~isfield(search, "method") || ...
            ~isfield(search, "status") || ...
            string(search.method) ~= "ga" || ...
            string(search.status) ~= "completed" || ...
            ~isfield(search, "improvementOverSeed") || ...
            ~isscalar(search.improvementOverSeed) || ...
            ~isfinite(double(search.improvementOverSeed))
        continue
    end
    diagnostics.eligible = diagnostics.eligible + 1;
    diagnostics.improved = diagnostics.improved + ...
        (double(search.improvementOverSeed) > 1e-12);
end
end

function plotHypervolumeHistories(histories, labels, outputRoot)
figureHandle = figure("Visible", "off", "Color", "w", ...
    "Position", [100, 100, 1300, 820]);
layout = tiledlayout(figureHandle, 2, 4, ...
    "TileSpacing", "compact", "Padding", "compact");
colors = lines(5);
legendAxes = [];
legendHandles = gobjects(0);
for problemIndex = 1:numel(histories)
    axesHandle = nexttile(layout);
    hold(axesHandle, "on");
    values = histories{problemIndex};
    handles = gobjects(5, 1);
    for replicateIndex = 1:5
        handles(replicateIndex) = plot(axesHandle, 0:130, ...
            values(:, replicateIndex), "Color", ...
            [colors(replicateIndex, :), 0.58], "LineWidth", 0.8);
    end
    plot(axesHandle, 0:130, median(values, 2), "k-", ...
        "LineWidth", 2.0);
    xlim(axesHandle, [0, 130]);
    grid(axesHandle, "on");
    title(axesHandle, labels(problemIndex), "FontSize", 10);
    xlabel(axesHandle, "sequential evaluations");
    ylabel(axesHandle, "normalized HV");
    if problemIndex == 1
        legendAxes = axesHandle;
        legendHandles = handles;
    end
end
legend(legendAxes, legendHandles, ...
    {"seed 1", "seed 2", "seed 3", "seed 4", "seed 5"}, ...
    "Location", "southeast", "FontSize", 7);
figureDirectory = fullfile(outputRoot, "figures");
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end
exportgraphics(figureHandle, fullfile(figureDirectory, ...
    "hypervolume_histories.png"), "Resolution", 300);
exportgraphics(figureHandle, fullfile(figureDirectory, ...
    "hypervolume_histories.pdf"), ...
    "ContentType", "vector");
close(figureHandle);
end

function plotSelectionSources(summary, labels, outputRoot)
figureHandle = figure("Visible", "off", "Color", "w", ...
    "Position", [100, 100, 1250, 460]);
layout = tiledlayout(figureHandle, 1, 2, ...
    "TileSpacing", "compact", "Padding", "compact");

axesHandle = nexttile(layout);
bar(axesHandle, 100 .* summary.ChallengerOverrideRate, ...
    "FaceColor", [0.24, 0.55, 0.78]);
xticks(axesHandle, 1:height(summary));
xticklabels(axesHandle, labels);
xtickangle(axesHandle, 24);
ylabel(axesHandle, "challenger overrides (%)");
grid(axesHandle, "on");

axesHandle = nexttile(layout);
bar(axesHandle, 100 .* summary.FallbackRate, ...
    "FaceColor", [0.88, 0.43, 0.16]);
xticks(axesHandle, 1:height(summary));
xticklabels(axesHandle, labels);
xtickangle(axesHandle, 24);
ylabel(axesHandle, "fallback selections (%)");
grid(axesHandle, "on");

exportgraphics(figureHandle, fullfile(outputRoot, ...
    "ga_primary_highdim_selection_sources.png"), "Resolution", 300);
exportgraphics(figureHandle, fullfile(outputRoot, ...
    "ga_primary_highdim_selection_sources.pdf"), ...
    "ContentType", "vector");
close(figureHandle);
end

function plotFinalFronts(fronts, labels, outputRoot)
figureHandle = figure("Visible", "off", "Color", "w", ...
    "Position", [100, 100, 1300, 820]);
layout = tiledlayout(figureHandle, 2, 4, ...
    "TileSpacing", "compact", "Padding", "compact");
colors = lines(5);
for problemIndex = 1:numel(fronts)
    axesHandle = nexttile(layout);
    hold(axesHandle, "on");
    problemFronts = fronts{problemIndex};
    for replicateIndex = 1:5
        front = problemFronts{replicateIndex};
        scatter(axesHandle, front(:, 1), front(:, 2), 16, ...
            colors(replicateIndex, :), "filled", ...
            "MarkerFaceAlpha", 0.62, "MarkerEdgeAlpha", 0.62);
    end
    axis(axesHandle, [0, 1.03, 0, 1.03]);
    axis(axesHandle, "square");
    grid(axesHandle, "on");
    title(axesHandle, labels(problemIndex), "FontSize", 10);
    xlabel(axesHandle, "normalized f_1");
    ylabel(axesHandle, "normalized f_2");
end
exportgraphics(figureHandle, fullfile(outputRoot, ...
    "ga_primary_highdim_final_fronts.png"), "Resolution", 300);
exportgraphics(figureHandle, fullfile(outputRoot, ...
    "ga_primary_highdim_final_fronts.pdf"), ...
    "ContentType", "vector");
close(figureHandle);
end
