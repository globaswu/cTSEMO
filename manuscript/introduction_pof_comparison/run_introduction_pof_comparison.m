    "LineWidth", 0.8, ...
    "GridAlpha", 0.12, ...
    "Layer", "top");
end

function writeSummary( ...
        pathValue, xTraining, yTraining, ...
        methodNames, metrics, gpcModel, ...
        gpcNegativeLogEvidence, knnBandwidth, ...
        ctsemoOptions, ctsemoFitDiagnostics)
fileId = fopen(pathValue, "w");
assert(fileId >= 0, "Could not open SUMMARY.txt for writing.");
closeFile = onCleanup(@() fclose(fileId));
fprintf(fileId, "Introduction PoF comparison\n");
fprintf(fileId, ...
    "Script: manuscript/introduction_pof_comparison/" + ...
    "run_introduction_pof_comparison.m\n\n");
fprintf(fileId, "Fixed random seed: 20260728\n");
fprintf(fileId, "Training observations: %d\n", size(xTraining, 1));
fprintf(fileId, "Feasible observations: %d\n", nnz(yTraining));
fprintf(fileId, "Violating observations: %d\n\n", nnz(~yTraining));
fprintf(fileId, "%s", ...
    "Constraint-wise product GP alone receives continuous " + ...
    "constraint margins. Every other method receives only the common " + ...
    "aggregate binary labels. The analytic boundary is displayed only " + ...
    "for diagnostics and is not used to tune any field." + newline + newline);
fprintf(fileId, "GPC length scale: %.8g\n", gpcModel.lengthScale);
