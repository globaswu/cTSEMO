function plotFeasibilityField( ...
        axesHandle, x1Grid, x2Grid, truthGrid, ...
        field, xTraining, yTraining)
imagesc(axesHandle, x1Grid(1, :), x2Grid(:, 1), field);
set(axesHandle, "YDir", "normal");
hold(axesHandle, "on");
contour(axesHandle, x1Grid, x2Grid, field, [0.5 0.5], ...
    "-", "Color", [1 1 1], "LineWidth", 1.1, ...
    "HandleVisibility", "off");
contour(axesHandle, x1Grid, x2Grid, truthGrid, [0.5 0.5], ...
    "--", "Color", [0.08 0.08 0.08], "LineWidth", 1.25, ...
    "HandleVisibility", "off");
scatter(axesHandle, ...
    xTraining(yTraining, 1), xTraining(yTraining, 2), ...
    48, [0.05 0.55 0.25], "o", "filled", ...
    "MarkerEdgeColor", "w", "LineWidth", 0.9, ...
    "HandleVisibility", "off");
plot(axesHandle, ...
    xTraining(~yTraining, 1), xTraining(~yTraining, 2), ...
    "x", "Color", [0.80 0.08 0.08], ...
    "MarkerSize", 7.5, "LineWidth", 1.8, ...
    "HandleVisibility", "off");
hold(axesHandle, "off");
axis(axesHandle, "square");
xlim(axesHandle, [0 1]);
ylim(axesHandle, [0 1]);
xticks(axesHandle, 0:0.2:1);
yticks(axesHandle, 0:0.2:1);
clim(axesHandle, [0 1]);
colormap(axesHandle, turbo(256));
colorbarHandle = colorbar(axesHandle, "eastoutside");
colorbarHandle.Ticks = [0 0.5 1];
colorbarHandle.Label.String = "p_i(x)";
colorbarHandle.Label.Interpreter = "tex";
xlabel(axesHandle, "x_1");
ylabel(axesHandle, "x_2");
grid(axesHandle, "on");
box(axesHandle, "on");
end

