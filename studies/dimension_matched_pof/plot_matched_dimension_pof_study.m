function artifacts = ...
        plot_matched_dimension_pof_study(studyDirectory)
%PLOT_MATCHED_DIMENSION_POF_STUDY Plot fixed-budget PoF evidence.
%   The rank plane in the exported diagnostic figures is a score ordering,
%   not a geometric projection of the original design space.

arguments
    studyDirectory (1,1) string
end

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(fileparts(scriptDirectory));
releaseRoot = fullfile(repositoryRoot, "src");
addpath(releaseRoot, fullfile(releaseRoot, "benchmarks"));

runFile = fullfile(studyDirectory, "run_summary.csv");
metricFile = fullfile(studyDirectory, "field_metrics.csv");
if ~isfile(runFile) || ~isfile(metricFile)
    error("cTSEMO:DimensionStudyPlot:MissingInput", ...
        "The completed run_summary.csv and field_metrics.csv are required.");
end
runTable = readtable(runFile, "TextType", "string");
metricTable = readtable(metricFile, "TextType", "string");
validateCampaignTables(runTable, metricTable);

outputDirectory = fullfile(studyDirectory, "figures");
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

representatives = selectD4Representatives(runTable);
artifacts = strings(2 + height(representatives), 1);
artifacts(1) = plotPairedDimensionMetrics( ...
    metricTable, outputDirectory);
artifacts(2) = plotAllProblemMetrics( ...
    metricTable, outputDirectory);

writetable(representatives, ...
    fullfile(outputDirectory, "d4_representative_runs.csv"));
for rowIndex = 1:height(representatives)
    artifacts(2 + rowIndex) = plotD4Representative( ...
        representatives(rowIndex, :), metricTable, ...
        studyDirectory, outputDirectory);
end

writetable(table(artifacts, VariableNames="Artifact"), ...
    fullfile(outputDirectory, "figure_manifest.csv"));
end

function validateCampaignTables(runs, metrics)
requiredRun = [ ...
    "ProblemId", "Family", "Dimension", "Replicate", "Status", ...
    "TotalEvaluations", "FinalFeasibleCount", "FinalParetoCount", ...
    "ProbeSeed", "ProbeCount", "ResultFile", "PredictionFile"];
requiredMetric = [ ...
    "ProblemId", "Family", "Dimension", "Replicate", "Method", ...
    "AUC", "FalsePositiveRate", "FalseNegativeRate", ...
    "BalancedError", "Brier", "BalancedBrier", ...
    "ProbeFeasibleRate", "PredictionFile"];
if ~all(ismember(requiredRun, string(runs.Properties.VariableNames)))
    error("cTSEMO:DimensionStudyPlot:RunSchema", ...
        "run_summary.csv does not have the required schema.");
end
if ~all(ismember(requiredMetric, ...
        string(metrics.Properties.VariableNames)))
    error("cTSEMO:DimensionStudyPlot:MetricSchema", ...
        "field_metrics.csv does not have the required schema.");
end
if any(runs.Status ~= "completed")
    error("cTSEMO:DimensionStudyPlot:IncompleteCampaign", ...
        "All trajectories must be completed before plotting.");
end
if any(runs.TotalEvaluations ~= 150)
    error("cTSEMO:DimensionStudyPlot:EvaluationCount", ...
        "Every full-study trajectory must contain 150 evaluations.");
end
bounded = [ ...
    metrics.AUC, metrics.FalsePositiveRate, ...
    metrics.FalseNegativeRate, metrics.BalancedError, ...
    metrics.Brier, metrics.BalancedBrier, ...
    metrics.ProbeFeasibleRate];
if any(~isfinite(bounded), "all") || ...
        any(bounded < 0 | bounded > 1, "all")
    error("cTSEMO:DimensionStudyPlot:InvalidMetric", ...
        "Expected all plotted field metrics to lie in [0,1].");
end
end

function outputFile = plotPairedDimensionMetrics(metrics, outputDirectory)
methods = ["clipped_GP_mean", "offline_RF_proxy"];
methodTitles = ["Clipped GP mean", "Offline RF proxy"];
metricNames = [ ...
    "FalsePositiveRate", "FalseNegativeRate", ...
    "BalancedError", "AUC"];
metricTitles = [ ...
    "False-feasible rate (FPR)", ...
    "False-infeasible rate (FNR)", ...
    "Balanced error", "ROC AUC"];
pairs = struct( ...
    "Family", {"CF1", "C2DTLZ2_R02", "MW7"}, ...
    "LowDimension", {4, 4, 4}, ...
    "HighDimension", {10, 6, 6}, ...
    "Label", {"CF1", "C2-DTLZ2", "MW7"});
colors = [ ...
    0.00, 0.45, 0.70; ...
    0.84, 0.37, 0.00; ...
    0.00, 0.62, 0.45];
markers = ["o", "s", "^"];

figureHandle = figure( ...
    "Visible", "off", "Color", "white", ...
    "Position", [60, 60, 1680, 800]);
layout = tiledlayout(figureHandle, 2, 4, ...
    "TileSpacing", "compact", "Padding", "compact");
for methodIndex = 1:numel(methods)
    for metricIndex = 1:numel(metricNames)
        axisHandle = nexttile(layout);
        hold(axisHandle, "on");
        for pairIndex = 1:numel(pairs)
            family = string(pairs(pairIndex).Family);
            block = metrics( ...
                metrics.Method == methods(methodIndex) & ...
                metrics.Family == family, :);
            replicates = unique(block.Replicate, "stable");
            lowValues = nan(numel(replicates), 1);
            highValues = nan(numel(replicates), 1);
            for replicateIndex = 1:numel(replicates)
                selected = block.Replicate == ...
                    replicates(replicateIndex);
                low = block(selected & block.Dimension == ...
                    pairs(pairIndex).LowDimension, :);
                high = block(selected & block.Dimension == ...
                    pairs(pairIndex).HighDimension, :);
                if height(low) ~= 1 || height(high) ~= 1
                    continue
                end
                lowValues(replicateIndex) = ...
                    low.(metricNames(metricIndex));
                highValues(replicateIndex) = ...
                    high.(metricNames(metricIndex));
                plot(axisHandle, ...
                    [pairs(pairIndex).LowDimension, ...
                    pairs(pairIndex).HighDimension], ...
                    [lowValues(replicateIndex), ...
                    highValues(replicateIndex)], ...
                    "-", "Color", 0.65 .* colors(pairIndex, :) + 0.35, ...
                    "LineWidth", 0.8, "HandleVisibility", "off");
            end
            plot(axisHandle, ...
                [pairs(pairIndex).LowDimension, ...
                pairs(pairIndex).HighDimension], ...
                [median(lowValues, "omitnan"), ...
                median(highValues, "omitnan")], ...
                "-", "Color", colors(pairIndex, :), ...
                "Marker", markers(pairIndex), ...
                "MarkerFaceColor", colors(pairIndex, :), ...
                "LineWidth", 2.2, ...
                "DisplayName", string(pairs(pairIndex).Label));
        end

        weldedBeam = metrics( ...
            metrics.Method == methods(methodIndex) & ...
            metrics.ProblemId == "WELDEDBEAM", :);
        if ~isempty(weldedBeam)
            scatter(axisHandle, ...
                4 .* ones(height(weldedBeam), 1), ...
                weldedBeam.(metricNames(metricIndex)), ...
                22, [0.35, 0.35, 0.35], "d", "filled", ...
                "MarkerFaceAlpha", 0.55, ...
                "HandleVisibility", "off");
            scatter(axisHandle, 4, ...
                median(weldedBeam.(metricNames(metricIndex)), "omitnan"), ...
                70, [0.15, 0.15, 0.15], "d", "filled", ...
                "DisplayName", "Welded beam (unpaired D4)");
        end
        ylim(axisHandle, [0, 1]);
        xlim(axisHandle, [3.5, 10.5]);
        xticks(axisHandle, [4, 6, 10]);
        grid(axisHandle, "on");
        box(axisHandle, "on");
        if methodIndex == 2
            xlabel(axisHandle, "Input dimension");
        end
        if metricIndex == 1
            ylabel(axisHandle, methodTitles(methodIndex));
        end
        title(axisHandle, metricTitles(metricIndex));
        if methodIndex == 1 && metricIndex == 1
            legend(axisHandle, "Location", "best", ...
                "FontSize", 8);
        end
    end
end
title(layout, [ ...
    "Matched 20+130 evaluation PoF diagnostics; thin lines are seeds, " ...
    "thick lines are medians"]);
outputFile = string(fullfile(outputDirectory, ...
    "paired_dimension_gp_rf_metrics.png"));
exportgraphics(figureHandle, outputFile, "Resolution", 240);
exportgraphics(figureHandle, replace(outputFile, ".png", ".pdf"), ...
    "ContentType", "vector");
close(figureHandle);
end

function outputFile = plotAllProblemMetrics(metrics, outputDirectory)
problemIds = [ ...
    "WELDEDBEAM", "CF1_D4", "CF1_D10", ...
    "C2DTLZ2_D4_R02", "C2DTLZ2_D6_R02", ...
    "MW7_D4", "MW7_D6"];
