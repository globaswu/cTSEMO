function aggregate = aggregateMetrics(metrics)
if isempty(metrics)
    aggregate = table();
    return
end
problems = unique(metrics.ProblemId, "stable");
methods = unique(metrics.Method, "stable");
rows = repmat(emptyAggregateRow(), ...
    numel(problems) .* numel(methods), 1);
rowIndex = 0;
metricNames = [ ...
    "AUC", "AveragePrecision", "Brier", "BalancedBrier", ...
    "ECE10", "BalancedAccuracy", "BalancedError", ...
    "FalsePositiveRate", "FalseNegativeRate", ...
    "FalseDiscoveryRate", "DomainError", ...
    "ConfidentFalsePositiveRate", ...
    "ConfidentFalseNegativeRate", ...
    "PredictedFeasibleRate", "AmbiguousRate", ...
    "ZeroMass", "OneMass"];
for problemIndex = 1:numel(problems)
    for methodIndex = 1:numel(methods)
        selected = metrics.ProblemId == problems(problemIndex) & ...
            metrics.Method == methods(methodIndex);
        if ~any(selected)
            continue
        end
        block = metrics(selected, :);
        rowIndex = rowIndex + 1;
        rows(rowIndex).ProblemId = problems(problemIndex);
        rows(rowIndex).Family = block.Family(1);
        rows(rowIndex).Dimension = block.Dimension(1);
        rows(rowIndex).Method = methods(methodIndex);
        rows(rowIndex).Replicates = height(block);
        rows(rowIndex).ProbeFeasibleRate = ...
            mean(block.ProbeFeasibleRate, "omitnan");
        for metricIndex = 1:numel(metricNames)
            name = metricNames(metricIndex);
            rows(rowIndex).("Mean" + name) = ...
                mean(block.(name), "omitnan");
            rows(rowIndex).("Std" + name) = ...
                std(block.(name), "omitnan");
        end
    end
end
aggregate = struct2table(rows(1:rowIndex));
end

function paired = pairedDimensionDifferences(metrics)
if isempty(metrics)
    paired = table();
    return
end
pairs = struct( ...
    "Family", {"CF1", "C2DTLZ2_R02", "MW7"}, ...
    "LowDimension", {4, 4, 4}, ...
    "HighDimension", {10, 6, 6});
methods = unique(metrics.Method, "stable");
replicates = unique(metrics.Replicate, "stable");
rows = repmat(emptyPairedRow(), ...
    numel(pairs) .* numel(methods) .* numel(replicates), 1);
rowIndex = 0;
metricNames = [ ...
    "AUC", "AveragePrecision", "Brier", "BalancedBrier", "ECE10", ...
    "BalancedAccuracy", "BalancedError", ...
    "FalsePositiveRate", "FalseNegativeRate", ...
    "FalseDiscoveryRate", "DomainError", ...
    "ConfidentFalsePositiveRate", ...
    "ConfidentFalseNegativeRate", ...
    "PredictedFeasibleRate", "AmbiguousRate", ...
    "ZeroMass", "OneMass"];
for pairIndex = 1:numel(pairs)
    for methodIndex = 1:numel(methods)
        for replicateIndex = 1:numel(replicates)
            common = metrics.Family == pairs(pairIndex).Family & ...
                metrics.Method == methods(methodIndex) & ...
                metrics.Replicate == replicates(replicateIndex);
            low = metrics(common & ...
                metrics.Dimension == pairs(pairIndex).LowDimension, :);
            high = metrics(common & ...
                metrics.Dimension == pairs(pairIndex).HighDimension, :);
            if height(low) ~= 1 || height(high) ~= 1
                continue
            end
            rowIndex = rowIndex + 1;
            rows(rowIndex).Family = string(pairs(pairIndex).Family);
            rows(rowIndex).Method = methods(methodIndex);
            rows(rowIndex).Replicate = replicates(replicateIndex);
            rows(rowIndex).LowDimension = ...
                pairs(pairIndex).LowDimension;
            rows(rowIndex).HighDimension = ...
                pairs(pairIndex).HighDimension;
            rows(rowIndex).LowPrevalence = low.ProbeFeasibleRate;
            rows(rowIndex).HighPrevalence = high.ProbeFeasibleRate;
            for metricIndex = 1:numel(metricNames)
                name = metricNames(metricIndex);
                rows(rowIndex).("Low" + name) = low.(name);
                rows(rowIndex).("High" + name) = high.(name);
                rows(rowIndex).("Delta" + name) = ...
                    high.(name) - low.(name);
            end
        end
    end
end
paired = struct2table(rows(1:rowIndex));
end

function aggregate = aggregatePairedDifferences(paired)
if isempty(paired)
    aggregate = table();
    return
end
metricNames = [ ...
    "AUC", "AveragePrecision", "Brier", "BalancedBrier", "ECE10", ...
    "BalancedAccuracy", "BalancedError", ...
    "FalsePositiveRate", "FalseNegativeRate", ...
    "FalseDiscoveryRate", "DomainError", ...
    "ConfidentFalsePositiveRate", ...
    "ConfidentFalseNegativeRate", ...
    "PredictedFeasibleRate", "AmbiguousRate", ...
    "ZeroMass", "OneMass"];
families = unique(paired.Family, "stable");
methods = unique(paired.Method, "stable");
rows = repmat(emptyPairedAggregateRow(), ...
    numel(families) .* numel(methods) .* numel(metricNames), 1);
rowIndex = 0;
for familyIndex = 1:numel(families)
    for methodIndex = 1:numel(methods)
        block = paired( ...
            paired.Family == families(familyIndex) & ...
            paired.Method == methods(methodIndex), :);
        if isempty(block)
            continue
        end
        for metricIndex = 1:numel(metricNames)
            metric = metricNames(metricIndex);
            low = block.("Low" + metric);
            high = block.("High" + metric);
            delta = block.("Delta" + metric);
            valid = isfinite(low) & isfinite(high) & isfinite(delta);
            rowIndex = rowIndex + 1;
            rows(rowIndex).Family = families(familyIndex);
            rows(rowIndex).Method = methods(methodIndex);
            rows(rowIndex).Metric = metric;
            rows(rowIndex).LowDimension = block.LowDimension(1);
            rows(rowIndex).HighDimension = block.HighDimension(1);
            rows(rowIndex).ValidN = nnz(valid);
            rows(rowIndex).LowMedian = median(low(valid), "omitnan");
            rows(rowIndex).HighMedian = median(high(valid), "omitnan");
            rows(rowIndex).MedianDelta = median(delta(valid), "omitnan");
            rows(rowIndex).MeanDelta = mean(delta(valid), "omitnan");
            rows(rowIndex).StdDelta = std(delta(valid), "omitnan");
            rows(rowIndex).PositiveDeltaCount = nnz(delta(valid) > 0);
            rows(rowIndex).NegativeDeltaCount = nnz(delta(valid) < 0);
            rows(rowIndex).ZeroDeltaCount = nnz(delta(valid) == 0);
        end
    end
end
aggregate = struct2table(rows(1:rowIndex));
end

