function writeJson(pathValue, value)
textValue = jsonencode(value, "PrettyPrint", true);
temporary = string(tempname(fileparts(pathValue))) + ".json";
fileId = fopen(temporary, "w");
if fileId < 0
    error("cTSEMO:DimensionStudy:JsonOpenFailure", ...
        "Could not open a temporary JSON file for '%s'.", pathValue);
end
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s\n", textValue);
clear cleanup
[success, message] = movefile(temporary, pathValue, "f");
if ~success
    error("cTSEMO:DimensionStudy:JsonCommitFailure", ...
        "Could not commit '%s': %s", pathValue, message);
end
end

function atomicWriteTable(value, pathValue)
temporary = string(tempname(fileparts(pathValue))) + ".csv";
writetable(value, temporary);
[success, message] = movefile(temporary, pathValue, "f");
if ~success
    error("cTSEMO:DimensionStudy:TableCommitFailure", ...
        "Could not commit '%s': %s", pathValue, message);
end
end

function atomicSave(pathValue, payload, version)
temporary = string(tempname(fileparts(pathValue))) + ".mat";
save(temporary, "-struct", "payload", version);
[success, message] = movefile(temporary, pathValue, "f");
if ~success
    error("cTSEMO:DimensionStudy:MatCommitFailure", ...
        "Could not commit '%s': %s", pathValue, message);
end
end

function value = sha256Text(textValue)
engine = java.security.MessageDigest.getInstance("SHA-256");
bytes = unicode2native(char(textValue), "UTF-8");
engine.update(bytes);
raw = typecast(engine.digest(), "uint8");
value = lower(string(reshape(dec2hex(raw, 2).', 1, [])));
end

