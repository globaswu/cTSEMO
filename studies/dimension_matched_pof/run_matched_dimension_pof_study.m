function family = familyForProblem(problemId)
id = string(problemId);
if startsWith(id, "CF1")
    family = "CF1";
elseif startsWith(id, "C2DTLZ2")
    family = "C2DTLZ2_R02";
elseif startsWith(id, "MW7")
    family = "MW7";
elseif id == "WELDEDBEAM"
    family = "WELDEDBEAM";
else
    error("cTSEMO:DimensionStudy:UnknownFamily", ...
        "No study family is defined for '%s'.", id);
end
end

function seed = probeSeedForProblem(problemId)
switch familyForProblem(problemId)
    case "WELDEDBEAM"
        seed = 2026073101;
    case "CF1"
        seed = 2026073102;
    case "C2DTLZ2_R02"
        seed = 2026073104;
    case "MW7"
        seed = 2026073106;
    otherwise
        error("cTSEMO:DimensionStudy:MissingProbeSeed", ...
            "No probe seed is registered for '%s'.", problemId);
end
end

function seed = rfSeedForProblem(problemId, replicate)
switch familyForProblem(problemId)
    case "WELDEDBEAM"
        base = 2026073500;
    case "CF1"
        base = 2026073600;
    case "C2DTLZ2_R02"
        base = 2026073800;
    case "MW7"
        base = 2026074000;
    otherwise
        error("cTSEMO:DimensionStudy:MissingRfSeed", ...
            "No RF seed is registered for '%s'.", problemId);
end
seed = base + replicate;
end

function ensureCompatibleManifest(pathValue, manifest)
if isfile(pathValue)
    existing = jsondecode(fileread(pathValue));
    hasSignatures = isfield(existing, "SourceSha256") && ...
        isfield(existing, "SettingsSha256");
    signaturesMatch = hasSignatures && ...
        string(existing.SourceSha256) == ...
        string(manifest.SourceSha256) && ...
        string(existing.SettingsSha256) == ...
        string(manifest.SettingsSha256);
    if ~signaturesMatch
        error("cTSEMO:DimensionStudy:IncompatibleResume", ...
            ["The existing study manifest does not match the current " ...
            "settings and source. Use a new StudyId."]);
    end
    return
end
writeJson(pathValue, manifest);
end

function [probeX, probeUnit, truth] = loadOrCreateProbes( ...
        pathValue, problem, count, seed)
if isfile(pathValue)
    stored = load(pathValue, "probeX", "probeUnit", "truth", ...
        "problemId", "probeSeed");
    probeX = stored.probeX;
    probeUnit = stored.probeUnit;
    truth = logical(stored.truth);
    if string(stored.problemId) ~= string(problem.id) || ...
            double(stored.probeSeed) ~= double(seed) || ...
            size(probeX, 1) ~= count || ...
            size(probeX, 2) ~= problem.dimension
        error("cTSEMO:DimensionStudy:ProbeRecordMismatch", ...
            "Stored probe record does not match the requested study.");
    end
    expectedUnit = normalizeToUnit( ...
        probeX, problem.lowerBound, problem.upperBound);
    if ~isequal(size(probeUnit), size(expectedUnit)) || ...
            max(abs(probeUnit - expectedUnit), [], "all") > 100 * eps
        error("cTSEMO:DimensionStudy:ProbeNormalizationMismatch", ...
            "Stored normalized probes disagree with current bounds.");
    end
    exactTruth = logical(problem.feasible(probeX));
    if ~isequal(truth, exactTruth)
        error("cTSEMO:DimensionStudy:ProbeTruthMismatch", ...
            "Stored probe truth disagrees with the benchmark.");
    end
    return
end

[probeX, ~] = initialDesign( ...
    problem, count, seed, struct("IncludeCorners", false));
probeUnit = normalizeToUnit( ...
    probeX, problem.lowerBound, problem.upperBound);
truth = logical(problem.feasible(probeX));
problemId = string(problem.id);
probeSeed = seed;
atomicSave(pathValue, struct( ...
    "probeX", probeX, ...
    "probeUnit", probeUnit, ...
    "truth", truth, ...
    "problemId", problemId, ...
    "probeSeed", probeSeed), "-v7.3");
end

function [loaded, runRow, metricRows] = loadCompletedRecord( ...
        pathValue, settingsSignature, sourceSignature)
loaded = false;
runRow = emptyRunRow();
metricRows = repmat(emptyMetricRow(), 0, 1);
if ~isfile(pathValue)
    return
end
try
    record = load(pathValue, ...
        "runRow", "perRunMetrics", ...
        "recordSettingsSignature", "recordSourceSignature");
catch
    return
end
if ~isfield(record, "runRow") || ...
        string(record.runRow.Status) ~= "completed"
    return
end
if ~isfield(record, "perRunMetrics") || ...
        numel(record.perRunMetrics) ~= 2
    return
end
if ~isfield(record, "recordSettingsSignature") || ...
        ~isfield(record, "recordSourceSignature") || ...
        string(record.recordSettingsSignature) ~= settingsSignature || ...
        string(record.recordSourceSignature) ~= sourceSignature || ...
        ~isfile(record.runRow.ResultFile) || ...
        ~isfile(record.runRow.PredictionFile)
    return
end
runRow = record.runRow;
metricRows = record.perRunMetrics;
loaded = true;
end

function score = predictGpInBatches(model, query, batchSize)
score = zeros(size(query, 1), 1);
for first = 1:batchSize:size(query, 1)
    last = min(size(query, 1), first + batchSize - 1);
    score(first:last) = ...
        ctsemo.predictClippedBinaryPof(model, query(first:last, :));
end
end

function probability = predictRfProxy( ...
        xTrain, labels, xQuery, dimension, seed, settings)
previousRandomState = rng;
restoreRandomState = onCleanup(@() rng(previousRandomState));
rng(double(seed), "twister");
if numel(unique(labels)) < 2
    background = (nnz(labels) + 1) ./ (numel(labels) + 2);
    probability = repmat(background, size(xQuery, 1), 1);
    return
end
learner = templateTree( ...
    "MinLeafSize", settings.RfMinLeafSize, ...
    "NumVariablesToSample", max(1, ceil(sqrt(dimension))));
model = fitcensemble( ...
    xTrain, labels, ...
    "Method", "Bag", ...
    "NumLearningCycles", settings.RfTrees, ...
    "Learners", learner, ...
    "ClassNames", [false true]);
positiveColumn = find(model.ClassNames == true, 1);
probability = zeros(size(xQuery, 1), 1);
for first = 1:settings.PredictionBatch:size(xQuery, 1)
    last = min(size(xQuery, 1), ...
        first + settings.PredictionBatch - 1);
    [~, score] = predict(model, xQuery(first:last, :));
    probability(first:last) = score(:, positiveColumn);
end
probability = min(1, max(0, probability));
clear restoreRandomState
end

function metrics = calculateFieldMetrics(truth, score)
truth = logical(truth(:));
score = double(score(:));
if isempty(truth) || numel(score) ~= numel(truth)
    error("cTSEMO:DimensionStudy:MetricInputSize", ...
        "Truth and score must be equal-length nonempty vectors.");
end
if any(~isfinite(score))
    error("cTSEMO:DimensionStudy:NonfiniteScore", ...
        "Field scores must be finite.");
end
score = min(1, max(0, score));
predicted = score >= 0.5;
positive = truth;
negative = ~truth;
tp = nnz(predicted & positive);
fp = nnz(predicted & negative);
fn = nnz(~predicted & positive);
tn = nnz(~predicted & negative);
positiveCount = nnz(positive);
negativeCount = nnz(negative);

metrics = struct( ...
    "TruePositive", tp, ...
    "FalsePositive", fp, ...
    "FalseNegative", fn, ...
    "TrueNegative", tn, ...
    "ProbeFeasibleCount", positiveCount, ...
    "ProbeInfeasibleCount", negativeCount, ...
    "ProbeFeasibleRate", mean(positive), ...
    "PredictedFeasibleRate", mean(predicted), ...
    "AUC", rocAuc(truth, score), ...
    "AveragePrecision", averagePrecision(truth, score), ...
    "Brier", mean((score - double(truth)) .^ 2), ...
    "BalancedBrier", 0.5 .* ( ...
        conditionalMean((score - 1) .^ 2, positive) + ...
        conditionalMean(score .^ 2, negative)), ...
    "ECE10", expectedCalibrationError(truth, score, 10), ...
    "FalsePositiveRate", safeDivide(fp, negativeCount), ...
    "FalseNegativeRate", safeDivide(fn, positiveCount), ...
    "FalseDiscoveryRate", safeDivide(fp, tp + fp), ...
    "BalancedAccuracy", 0.5 .* ( ...
        safeDivide(tp, positiveCount) + ...
        safeDivide(tn, negativeCount)), ...
    "BalancedError", 0.5 .* ( ...
        safeDivide(fp, negativeCount) + ...
        safeDivide(fn, positiveCount)), ...
    "DomainError", mean(predicted ~= truth), ...
    "ConfidentFalsePositiveRate", ...
        safeDivide(nnz(score > 2 / 3 & negative), negativeCount), ...
    "ConfidentFalseNegativeRate", ...
        safeDivide(nnz(score < 1 / 3 & positive), positiveCount), ...
    "AmbiguousRate", mean(score > 1 / 3 & score < 2 / 3), ...
    "ZeroMass", mean(score == 0), ...
    "OneMass", mean(score == 1));
end

function value = safeDivide(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator ./ denominator;
end
end

function value = conditionalMean(values, selected)
if any(selected)
    value = mean(values(selected));
else
    value = NaN;
end
end

function value = rocAuc(truth, score)
positiveCount = nnz(truth);
negativeCount = nnz(~truth);
if positiveCount == 0 || negativeCount == 0
    value = NaN;
    return
end
[sortedScore, order] = sort(score, "ascend");
ranks = (1:numel(score)).';
first = 1;
while first <= numel(sortedScore)
    last = first;
    while last < numel(sortedScore) && ...
            sortedScore(last + 1) == sortedScore(first)
        last = last + 1;
    end
    ranks(first:last) = 0.5 .* (first + last);
    first = last + 1;
end
unsortedRanks = zeros(size(ranks));
unsortedRanks(order) = ranks;
value = (sum(unsortedRanks(truth)) - ...
    positiveCount .* (positiveCount + 1) ./ 2) ./ ...
    (positiveCount .* negativeCount);
end

function value = averagePrecision(truth, score)
if ~any(truth)
    value = NaN;
    return
end
[sortedScore, order] = sort(score, "descend");
orderedTruth = truth(order);
truePositive = cumsum(orderedTruth);
groupEnd = [find(diff(sortedScore) ~= 0); numel(sortedScore)];
precision = truePositive(groupEnd) ./ groupEnd;
recall = truePositive(groupEnd) ./ nnz(truth);
value = sum(diff([0; recall]) .* precision);
end

function value = expectedCalibrationError(truth, score, binCount)
edges = linspace(0, 1, binCount + 1);
value = 0;
for binIndex = 1:binCount
    if binIndex < binCount
        inBin = score >= edges(binIndex) & ...
            score < edges(binIndex + 1);
    else
        inBin = score >= edges(binIndex) & ...
            score <= edges(binIndex + 1);
    end
    if any(inBin)
        value = value + mean(inBin) .* abs( ...
            mean(score(inBin)) - mean(truth(inBin)));
    end
end
end

function row = makeMetricRow(runRow, method, metrics)
row = emptyMetricRow();
row.ProblemId = runRow.ProblemId;
row.Family = runRow.Family;
row.Dimension = runRow.Dimension;
row.Replicate = runRow.Replicate;
row.Method = string(method);
row.ProbeSeed = runRow.ProbeSeed;
row.RfSeed = runRow.RfSeed;
row.ProbeCount = runRow.ProbeCount;
