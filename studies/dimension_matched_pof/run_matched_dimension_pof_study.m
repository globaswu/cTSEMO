function [runSummary, fieldMetrics, aggregate, paired, studyDirectory] = ...
        run_matched_dimension_pof_study(settings)
%RUN_MATCHED_DIMENSION_POF_STUDY Fixed-budget PoF dimension screen.
%   This study runs the current complete-pool cTSEMO implementation on
%   matched 4-D/higher-dimensional benchmark-family pairs and on welded
%   beam as an unpaired 4-D engineering anchor. Every run uses 20
%   corner-free LHS observations plus 130 sequential evaluations by
%   default. The final shipped clipped GP-mean field and an offline random
%   forest proxy are evaluated on identical independent volume probes.
%
%   SETTINGS is an optional scalar struct with these fields:
%     ProblemIds         default WB, CF1 D4/D10, C2-DTLZ2 D4/D6, MW7 D4/D6
%     Replicates         default 1:5
%     InitialCount       default 20
%     SequentialBudget   default 130
%     ProbeCount         default 262144 (512^2)
%     PredictionBatch    default 5000
%     PrimaryCount       default 1024
%     ChallengerCount    default 512
%     ObjectiveFeatures  default 256
%     RfTrees            default 120
%     RfMinLeafSize      default 3
%     StudyId            default unique run identifier
%     OutputRoot         default results below this script
%     ContinueOnFailure  default true
%
%   The RF proxy is fitted offline to the final GP-guided data. It is a
%   fixed-data diagnostic, not an online comparison of optimizer policies.

if nargin < 1 || isempty(settings)
    settings = struct();
end
settings = resolveSettings(settings);

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(fileparts(scriptDirectory));
releaseRoot = fullfile(repositoryRoot, "src");
benchmarkRoot = fullfile(releaseRoot, "benchmarks");
previousPath = path;
restorePath = onCleanup(@() path(previousPath));
addpath(releaseRoot, benchmarkRoot);

studyDirectory = string(fullfile(settings.OutputRoot, settings.StudyId));
createDirectory(studyDirectory);
createDirectory(fullfile(studyDirectory, "runs"));
createDirectory(fullfile(studyDirectory, "probes"));

sourceSignature = sha256Text(fileread(mfilename("fullpath") + ".m"));
settingsSignature = sha256Text(jsonencode(orderfields(settings)));
manifest = makeManifest( ...
    settings, sourceSignature, settingsSignature);
ensureCompatibleManifest( ...
    fullfile(studyDirectory, "study_manifest.json"), manifest);

runRows = repmat(emptyRunRow(), 0, 1);
metricRows = repmat(emptyMetricRow(), 0, 1);
problemIds = string(settings.ProblemIds(:)).';
replicates = reshape(double(settings.Replicates), 1, []);

for problemIndex = 1:numel(problemIds)
    problem = getBenchmarkProblem(problemIds(problemIndex));
    family = familyForProblem(problem.id);
    probeSeed = probeSeedForProblem(problem.id);
    probeFile = fullfile(studyDirectory, "probes", ...
        problem.id + "_volume_probes.mat");
    [~, probeUnit, probeTruth] = loadOrCreateProbes( ...
        probeFile, problem, settings.ProbeCount, probeSeed);

    for replicate = replicates
        initialSeed = 2026073200 + replicate;
        solverSeed = 2026073300 + replicate;
        rfSeed = rfSeedForProblem(problem.id, replicate);
        runKey = sprintf("%s_rep%02d", problem.id, replicate);
        runRoot = fullfile(studyDirectory, "runs", runKey);
        createDirectory(runRoot);
        recordFile = fullfile(runRoot, "campaign_record.mat");

        [wasLoaded, loadedRun, loadedMetrics] = ...
            loadCompletedRecord( ...
            recordFile, settingsSignature, sourceSignature);
        if wasLoaded
            runRows(end + 1, 1) = loadedRun; %#ok<AGROW>
            metricRows = [metricRows; loadedMetrics(:)]; %#ok<AGROW>
            continue
        end

        runRow = emptyRunRow();
        runRow.ProblemId = string(problem.id);
        runRow.Family = family;
        runRow.Dimension = problem.dimension;
        runRow.Replicate = replicate;
        runRow.Status = "pending";
        runRow.InitialSeed = initialSeed;
        runRow.SolverSeed = solverSeed;
        runRow.ProbeSeed = probeSeed;
        runRow.RfSeed = rfSeed;
        runRow.InitialCount = settings.InitialCount;
        runRow.SequentialBudget = settings.SequentialBudget;
        runRow.ProbeCount = settings.ProbeCount;
        runRow.ProbeFeasibleCount = nnz(probeTruth);
        runRow.ProbeInfeasibleCount = nnz(~probeTruth);
        runRow.ProbeFeasibleRate = mean(probeTruth);

        try
            [X0, designInfo] = initialDesign( ...
                problem, settings.InitialCount, initialSeed, ...
                struct("IncludeCorners", false));
            Y0 = problem.objective(X0);
            C0 = problem.label01(X0);
            runRow.InitialFeasibleCount = designInfo.FeasibleCount;

            overrides = struct( ...
                "maxEvaluations", settings.SequentialBudget, ...
                "seed", solverSeed, ...
                "feasibility", struct( ...
                    "inputEncoding", "feasibleIsOne"), ...
                "candidates", struct( ...
                    "primaryCount", settings.PrimaryCount, ...
                    "includeCorners", false), ...
                "objectiveGP", struct( ...
                    "nFeatures", settings.ObjectiveFeatures), ...
                "challengers", struct( ...
                    "enabled", true, ...
                    "count", settings.ChallengerCount, ...
                    "scoreCompletePools", true), ...
                "logging", struct( ...
                    "level", "summary", ...
                    "directory", string(runRoot), ...
                    "checkpoint", true, ...
                    "saveEveryIteration", false));
            options = cTSEMOOptions(overrides);

            result = cTSEMO( ...
                problem.objective, problem.label01, ...
                X0, Y0, C0, ...
                problem.lowerBound, problem.upperBound, options);
            resultFile = fullfile(result.meta.outputDirectory, "result.mat");
            if ~isfile(resultFile)
                error("cTSEMO:DimensionStudy:MissingResult", ...
                    "The solver did not save the expected result.mat file.");
            end

            labels = logical(result.data.isFeasible);
            if size(result.data.X, 1) ~= ...
                    settings.InitialCount + settings.SequentialBudget
                error("cTSEMO:DimensionStudy:WrongEvaluationCount", ...
                    "Expected %d observations but found %d.", ...
                    settings.InitialCount + settings.SequentialBudget, ...
                    size(result.data.X, 1));
            end
            exactLabels = logical(problem.feasible(result.data.X));
            if ~isequal(labels, exactLabels)
                error("cTSEMO:DimensionStudy:StoredLabelMismatch", ...
                    "Stored feasibility labels disagree with benchmark truth.");
            end

            trainUnit = normalizeToUnit( ...
                result.data.X, problem.lowerBound, problem.upperBound);
            [gpModel, gpFit] = ctsemo.fitClippedBinaryPof( ...
                trainUnit, labels, result.options);
            gpScore = predictGpInBatches( ...
                gpModel, probeUnit, settings.PredictionBatch);
            rfScore = predictRfProxy( ...
                trainUnit, labels, probeUnit, ...
                problem.dimension, rfSeed, settings);

            gpMetrics = calculateFieldMetrics(probeTruth, gpScore);
            rfMetrics = calculateFieldMetrics(probeTruth, rfScore);
            gpRow = makeMetricRow( ...
                runRow, "clipped_GP_mean", gpMetrics);
            rfRow = makeMetricRow( ...
                runRow, "offline_RF_proxy", rfMetrics);
            perRunMetrics = [gpRow; rfRow];

            runRow = summarizeSolverRun( ...
                runRow, result, gpFit, resultFile);
            runRow.Status = "completed";

            predictionFile = fullfile(runRoot, "probe_predictions.mat");
            atomicSave(predictionFile, ...
                struct("gpScore", gpScore, "rfScore", rfScore), "-v7");
            runRow.PredictionFile = string(predictionFile);
            perRunMetrics(1).PredictionFile = string(predictionFile);
            perRunMetrics(2).PredictionFile = string(predictionFile);
            recordSettingsSignature = settingsSignature;
            recordSourceSignature = sourceSignature;
            atomicSave(recordFile, struct( ...
                "runRow", runRow, ...
                "perRunMetrics", perRunMetrics, ...
                "recordSettingsSignature", recordSettingsSignature, ...
                "recordSourceSignature", recordSourceSignature), "-v7");
        catch exception
            runRow.Status = "failed";
            runRow.ErrorIdentifier = string(exception.identifier);
            runRow.ErrorMessage = string(exception.message);
            failure = struct( ...
                "identifier", string(exception.identifier), ...
                "message", string(exception.message), ...
                "report", string(getReport(exception, "extended")));
            atomicSave(fullfile(runRoot, "campaign_failure.mat"), ...
                struct("runRow", runRow, "failure", failure), "-v7");
            perRunMetrics = repmat(emptyMetricRow(), 0, 1);
            if ~settings.ContinueOnFailure
                runRows(end + 1, 1) = runRow; %#ok<AGROW>
                writeCheckpoint( ...
                    studyDirectory, runRows, metricRows, settings);
                rethrow(exception)
            end
        end

        runRows(end + 1, 1) = runRow; %#ok<AGROW>
        metricRows = [metricRows; perRunMetrics(:)]; %#ok<AGROW>
        writeCheckpoint(studyDirectory, runRows, metricRows, settings);
    end
end

runSummary = struct2table(runRows);
fieldMetrics = struct2table(metricRows);
aggregate = aggregateMetrics(fieldMetrics);
paired = pairedDimensionDifferences(fieldMetrics);
pairedAggregate = aggregatePairedDifferences(paired);
atomicWriteTable(runSummary, ...
    fullfile(studyDirectory, "run_summary.csv"));
atomicWriteTable(fieldMetrics, ...
    fullfile(studyDirectory, "field_metrics.csv"));
atomicWriteTable(aggregate, ...
    fullfile(studyDirectory, "aggregate_summary.csv"));
atomicWriteTable(paired, ...
    fullfile(studyDirectory, "paired_dimension_differences.csv"));
atomicWriteTable(pairedAggregate, ...
    fullfile(studyDirectory, "paired_aggregate_summary.csv"));
atomicSave(fullfile(studyDirectory, "study_results.mat"), struct( ...
    "runSummary", runSummary, ...
    "fieldMetrics", fieldMetrics, ...
    "aggregate", aggregate, ...
    "paired", paired, ...
    "pairedAggregate", pairedAggregate, ...
    "settings", settings, ...
    "manifest", manifest), "-v7");
end

function settings = resolveSettings(overrides)
scriptDirectory = fileparts(mfilename("fullpath"));
defaults = struct( ...
    "ProblemIds", [ ...
        "WELDEDBEAM", ...
        "CF1_D4", "CF1_D10", ...
        "C2DTLZ2_D4_R02", "C2DTLZ2_D6_R02", ...
        "MW7_D4", "MW7_D6"], ...
    "Replicates", 1:5, ...
    "InitialCount", 20, ...
    "SequentialBudget", 130, ...
    "ProbeCount", 262144, ...
    "PredictionBatch", 5000, ...
    "PrimaryCount", 1024, ...
    "ChallengerCount", 512, ...
    "ObjectiveFeatures", 256, ...
    "RfTrees", 120, ...
    "RfMinLeafSize", 3, ...
    "StudyId", "", ...
    "OutputRoot", string(fullfile(scriptDirectory, "results")), ...
    "ContinueOnFailure", true);
validateattributes(overrides, {'struct'}, {'scalar'}, ...
    mfilename, "settings");
names = fieldnames(overrides);
settings = defaults;
for index = 1:numel(names)
    name = names{index};
    if ~isfield(defaults, name)
        error("cTSEMO:DimensionStudy:UnknownSetting", ...
            "Unknown setting '%s'.", name);
    end
    settings.(name) = overrides.(name);
end

validateattributes(settings.ProblemIds, {'char', 'string'}, ...
    {'nonempty'}, mfilename, "settings.ProblemIds");
integerFields = [ ...
    "InitialCount", "SequentialBudget", "ProbeCount", ...
    "PredictionBatch", "PrimaryCount", "ChallengerCount", ...
    "ObjectiveFeatures", "RfTrees", "RfMinLeafSize"];
for index = 1:numel(integerFields)
    validateattributes(settings.(integerFields(index)), {'numeric'}, ...
        {'scalar', 'integer', 'positive', 'finite'}, ...
        mfilename, "settings." + integerFields(index));
end
validateattributes(settings.Replicates, {'numeric'}, ...
    {'vector', 'integer', 'positive', 'finite'}, ...
    mfilename, "settings.Replicates");
validateattributes(settings.OutputRoot, {'char', 'string'}, ...
    {'scalartext'}, mfilename, "settings.OutputRoot");
validateattributes(settings.StudyId, {'char', 'string'}, ...
    {'scalartext'}, mfilename, "settings.StudyId");
if ~(islogical(settings.ContinueOnFailure) && ...
        isscalar(settings.ContinueOnFailure))
    error("cTSEMO:DimensionStudy:InvalidContinueOnFailure", ...
        "ContinueOnFailure must be a logical scalar.");
end
settings.ProblemIds = string(settings.ProblemIds);
if numel(unique(settings.ProblemIds)) ~= numel(settings.ProblemIds)
    error("cTSEMO:DimensionStudy:DuplicateProblem", ...
        "ProblemIds must not contain duplicates.");
end
if numel(unique(settings.Replicates)) ~= numel(settings.Replicates)
    error("cTSEMO:DimensionStudy:DuplicateReplicate", ...
        "Replicates must not contain duplicates.");
end
settings.OutputRoot = string(settings.OutputRoot);
settings.StudyId = string(settings.StudyId);
if strlength(settings.StudyId) == 0
    settings.StudyId = "matched_dimension_pof_" + ...
        string(datetime("now", "Format", "yyyyMMdd_HHmmss_SSS"));
end
end

