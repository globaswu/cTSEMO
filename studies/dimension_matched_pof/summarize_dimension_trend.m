    "MedianPredictedFeasibleRate", NaN, ...
    "MedianAUC", NaN, "MedianAveragePrecision", NaN, ...
    "MedianBrier", NaN, "MedianBalancedBrier", NaN, ...
    "MedianECE10", NaN, "MedianFalsePositiveRate", NaN, ...
    "MedianFalseNegativeRate", NaN, ...
    "MedianFalseDiscoveryRate", NaN, ...
    "MedianBalancedAccuracy", NaN, ...
    "MedianBalancedError", NaN, "MedianDomainError", NaN, ...
    "MedianAmbiguousRate", NaN, "MedianZeroMass", NaN);
