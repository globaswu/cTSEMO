function plotPofMap(axesHandle, map, showTruthBoundary, showObservations)
imagesc(axesHandle, map.UnitX1(1, :), map.UnitX2(:, 1), map.Score);
set(axesHandle, "YDir", "normal");
colormap(axesHandle, turbo(256));
clim(axesHandle, [0, 1]);
hold(axesHandle, "on");
contour(axesHandle, map.UnitX1(1, :), map.UnitX2(:, 1), ...
