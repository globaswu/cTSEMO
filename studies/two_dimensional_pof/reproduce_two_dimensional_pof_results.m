function writeSourceManifest(repositoryRoot, studyFile, artifactRoot)
sourceRoot = fullfile(repositoryRoot, "src");
sourceFiles = dir(fullfile(sourceRoot, "**", "*.m"));
absolutePaths = string(fullfile({sourceFiles.folder}, {sourceFiles.name}))';
absolutePaths = [ ...
    string(fullfile(repositoryRoot, "setup_ctsemo.m")); ...
    string(studyFile) + ".m"; ...
    absolutePaths];
absolutePaths = unique(absolutePaths, "stable");

relativePaths = strings(size(absolutePaths));
categories = strings(size(absolutePaths));
bytes = zeros(size(absolutePaths));
digests = strings(size(absolutePaths));
for index = 1:numel(absolutePaths)
    if ~isfile(absolutePaths(index))
        error("cTSEMO:TwoDimensionalStudy:MissingSource", ...
            "Source file missing while sealing manifest: %s", ...
            absolutePaths(index));
    end
    relativePaths(index) = replace(erase(absolutePaths(index), ...
        repositoryRoot + filesep), "\", "/");
    if startsWith(relativePaths(index), "studies/")
        categories(index) = "study";
    elseif startsWith(relativePaths(index), "src/benchmarks/")
        categories(index) = "benchmark";
    elseif startsWith(relativePaths(index), "src/tests/")
        categories(index) = "test";
    else
        categories(index) = "release";
    end
    fileInfo = dir(absolutePaths(index));
    bytes(index) = fileInfo.bytes;
    digests(index) = sha256File(absolutePaths(index));
end
sourceManifest = table( ...
    categories, relativePaths, bytes, digests, ...
    VariableNames=["Category", "RelativePath", "Bytes", "SHA256"]);
sourceManifest = sortrows(sourceManifest, "RelativePath");
writetable(sourceManifest, fullfile(artifactRoot, "source_manifest.csv"));
manifestPath = fullfile(artifactRoot, "source_manifest.csv");
manifestDigest = sha256File(manifestPath);
writeText(fullfile(artifactRoot, "source_manifest.sha256"), ...
    manifestDigest + "  source_manifest.csv" + newline);
writeJson(fullfile(artifactRoot, "source_manifest.json"), ...
    table2struct(sourceManifest));
end

