function value = binaryAuc(truth, score)
truth = logical(truth(:));
score = score(:);
positiveCount = nnz(truth);
negativeCount = nnz(~truth);
if positiveCount == 0 || negativeCount == 0
    value = NaN;
    return
end
[sortedScore, order] = sort(score, "ascend");
ranks = zeros(size(score));
startIndex = 1;
while startIndex <= numel(score)
    endIndex = startIndex;
    while endIndex < numel(score) && ...
            sortedScore(endIndex + 1) == sortedScore(startIndex)
        endIndex = endIndex + 1;
    end
    meanRank = 0.5 .* (startIndex + endIndex);
    ranks(order(startIndex:endIndex)) = meanRank;
    startIndex = endIndex + 1;
end
value = (sum(ranks(truth)) - ...
    positiveCount .* (positiveCount + 1) ./ 2) ./ ...
    (positiveCount .* negativeCount);
end

function value = expectedCalibrationError(truth, score, binCount)
edges = linspace(0, 1, binCount + 1);
value = 0;
for binIndex = 1:binCount
    if binIndex < binCount
        inBin = score >= edges(binIndex) & score < edges(binIndex + 1);
    else
        inBin = score >= edges(binIndex) & score <= edges(binIndex + 1);
    end
    if any(inBin)
        value = value + mean(inBin) .* abs( ...
            mean(score(inBin)) - mean(truth(inBin)));
    end
end
end

function value = safeRatio(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator ./ denominator;
end
end

