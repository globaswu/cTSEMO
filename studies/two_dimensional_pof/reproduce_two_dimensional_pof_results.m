function results = runCampaign(definitions, stableRunDirectory, logRoot)
results = cell(numel(definitions), 1);
for caseIndex = 1:numel(definitions)
    definition = definitions(caseIndex);
    problem = getBenchmarkProblem(definition.ProblemId);
    [X0, designInfo] = initialDesign( ...
        problem, definition.InitialCount, definition.InitialSeed, ...
        struct("IncludeCorners", true, "AllInfeasible", false));
    Y0 = problem.objective(X0);
    C0 = problem.label01(X0);

    caseLogRoot = fullfile(logRoot, definition.Id);
    ensureDirectory(caseLogRoot);
    options = cTSEMOOptions(struct( ...
        "maxEvaluations", definition.SequentialBudget, ...
        "seed", definition.SolverSeed, ...
        "feasibility", struct("inputEncoding", "feasibleIsOne"), ...
        "candidates", struct("primaryCount", 1024), ...
        "primarySearch", struct( ...
            "method", "ga", ...
            "populationSize", 80, ...
            "eliteCount", 2, ...
            "maxGenerations", 120, ...
            "maxStallGenerations", 30, ...
            "functionTolerance", 1.0e-8, ...
            "useParallel", false, ...
            "failurePolicy", "error"), ...
        "objectiveGP", struct("nFeatures", 256), ...
        "challengers", struct( ...
            "enabled", true, ...
            "count", 512, ...
            "scoreCompletePools", true), ...
        "logging", struct( ...
            "level", "full", ...
            "directory", string(caseLogRoot), ...
            "checkpoint", false, ...
            "saveEveryIteration", true)));

    fprintf("Running %s: %d initial + %d sequential evaluations.\n", ...
        definition.Id, definition.InitialCount, ...
        definition.SequentialBudget);
    result = cTSEMO( ...
        problem.objective, problem.label01, X0, Y0, C0, ...
        problem.lowerBound, problem.upperBound, options);
    validateCompletedResult(result, problem, definition);

    result.meta.outputDirectory = "@RUNTIME_LOG_ROOT@";
    result.options.logging.directory = "@RUNTIME_LOG_ROOT@";
    problemRecord = serializableProblem(problem);
    runConfiguration = definition;
    stablePath = fullfile(stableRunDirectory, ...
        definition.Id + "_result.mat");
    save(stablePath, "result", "problemRecord", ...
        "designInfo", "runConfiguration", "-v7.3");
    results{caseIndex} = result;
end
end

function results = loadStableResults(definitions, stableRunDirectory)
results = cell(numel(definitions), 1);
for caseIndex = 1:numel(definitions)
    definition = definitions(caseIndex);
    stablePath = fullfile(stableRunDirectory, ...
        definition.Id + "_result.mat");
    if ~isfile(stablePath)
        error("cTSEMO:TwoDimensionalStudy:MissingStableResult", ...
            "ReuseResults requested, but this file is missing: %s", ...
            stablePath);
    end
    loaded = load(stablePath, "result");
    results{caseIndex} = loaded.result;
end
end

function validateCompletedResult(result, problem, definition)
expectedCount = definition.InitialCount + definition.SequentialBudget;
if string(result.meta.status) ~= "completed"
    error("cTSEMO:TwoDimensionalStudy:IncompleteResult", ...
        "%s has result status '%s'.", definition.Id, result.meta.status);
end
if size(result.data.X, 1) ~= expectedCount
    error("cTSEMO:TwoDimensionalStudy:EvaluationCountMismatch", ...
        "%s returned %d evaluations; %d were required.", ...
        definition.Id, size(result.data.X, 1), expectedCount);
end
if result.data.nInitial ~= definition.InitialCount
    error("cTSEMO:TwoDimensionalStudy:InitialCountMismatch", ...
        "%s stored %d initial evaluations; %d were required.", ...
        definition.Id, result.data.nInitial, definition.InitialCount);
end
truth = logical(problem.feasible(result.data.X));
if ~isequal(truth, logical(result.data.isFeasible))
    error("cTSEMO:TwoDimensionalStudy:TruthLabelMismatch", ...
        "%s stored labels disagree with exact benchmark truth.", ...
        definition.Id);
end
if result.options.candidates.primaryCount ~= 1024 || ...
        result.options.challengers.count ~= 512 || ...
        result.options.objectiveGP.nFeatures ~= 256 || ...
        ~result.options.challengers.scoreCompletePools || ...
        string(result.options.logging.level) ~= "full"
    error("cTSEMO:TwoDimensionalStudy:ProtocolMismatch", ...
        "%s does not contain the frozen current-source protocol.", ...
        definition.Id);
end
end

function [map, metric] = evaluatePofField( ...
        problem, result, prefixCount, unitGrid, U1, U2, phase)
lowerBound = problem.lowerBound;
upperBound = problem.upperBound;
X = result.data.X(1:prefixCount, :);
labels = logical(result.data.isFeasible(1:prefixCount));
unitX = (X - lowerBound) ./ (upperBound - lowerBound);
physicalGrid = lowerBound + unitGrid .* (upperBound - lowerBound);
truth = logical(problem.feasible(physicalGrid));

[model, fitDiagnostics] = ctsemo.fitClippedBinaryPof( ...
    unitX, labels, result.options);
[score, rawMean, predictionDiagnostics] = ...
    ctsemo.predictClippedBinaryPof(model, unitGrid);
anchorScore = ctsemo.predictClippedBinaryPof(model, unitX);
% Equality is classified as feasible to match the manuscript decision rule.
predictedFeasible = score >= 0.5;
errorClass = classifyField(predictedFeasible, truth);

metric = makeMetricRow( ...
    problem.id, phase, prefixCount, result.data.nInitial, ...
    labels, truth, score, rawMean, predictedFeasible, ...
    anchorScore, fitDiagnostics);

map = struct( ...
    "ProblemId", string(problem.id), ...
    "ProblemName", string(problem.name), ...
    "Phase", string(phase), ...
    "TotalEvaluations", prefixCount, ...
    "SequentialEvaluations", prefixCount - result.data.nInitial, ...
    "UnitX1", U1, ...
    "UnitX2", U2, ...
    "PhysicalX1", reshape(physicalGrid(:, 1), size(U1)), ...
    "PhysicalX2", reshape(physicalGrid(:, 2), size(U2)), ...
    "Score", reshape(score, size(U1)), ...
    "RawMean", reshape(rawMean, size(U1)), ...
    "Truth", reshape(truth, size(U1)), ...
    "PredictedFeasible", reshape(predictedFeasible, size(U1)), ...
    "ErrorClass", reshape(errorClass, size(U1)), ...
    "LocalLength", reshape( ...
        predictionDiagnostics.localLength, size(U1)), ...
    "ObservedUnitX", unitX, ...
    "ObservedPhysicalX", X, ...
    "ObservedFeasible", labels, ...
    "FitDiagnostics", fitDiagnostics);
end

function metric = makeMetricRow( ...
        problemId, phase, prefixCount, initialCount, observedLabels, ...
        truth, score, rawMean, predicted, anchorScore, fitDiagnostics)
truePositive = nnz(predicted & truth);
trueNegative = nnz(~predicted & ~truth);
falsePositive = nnz(predicted & ~truth);
falseNegative = nnz(~predicted & truth);
positiveCount = nnz(truth);
negativeCount = nnz(~truth);

truePositiveRate = safeRatio(truePositive, positiveCount);
trueNegativeRate = safeRatio(trueNegative, negativeCount);
metric = emptyMetricRow();
metric.ProblemId = string(problemId);
metric.Phase = string(phase);
metric.TotalEvaluations = prefixCount;
metric.SequentialEvaluations = prefixCount - initialCount;
metric.FeasibleObserved = nnz(observedLabels);
metric.ViolatingObserved = nnz(~observedLabels);
metric.GridPointCount = numel(truth);
metric.ExactFeasibleGridFraction = mean(truth);
metric.MeanScore = mean(score);
metric.AUC = binaryAuc(truth, score);
metric.Brier = mean((score - double(truth)).^2);
metric.ECE10 = expectedCalibrationError(truth, score, 10);
metric.FalseFeasibleRate = safeRatio(falsePositive, negativeCount);
metric.FalseInfeasibleRate = safeRatio(falseNegative, positiveCount);
metric.BalancedAccuracy = 0.5 .* ...
    (truePositiveRate + trueNegativeRate);
metric.OverallMisclassificationRate = ...
    (falsePositive + falseNegative) ./ numel(truth);
metric.AnchorMaxAbsoluteError = ...
    max(abs(anchorScore - double(observedLabels)));
metric.FractionAtZero = mean(score == 0);
metric.FractionAtOne = mean(score == 1);
metric.RawMeanMinimum = min(rawMean);
metric.RawMeanMaximum = max(rawMean);
metric.BaseLengthScale = fitDiagnostics.baseLength;
metric.LocalLengthMinimum = fitDiagnostics.trainingLengthMinimum;
metric.LocalLengthMaximum = fitDiagnostics.trainingLengthMaximum;
end

function errorClass = classifyField(predicted, truth)
% 0: correct violating; 1: false feasible; 2: false infeasible;
% 3: correct feasible.
errorClass = zeros(size(truth));
errorClass(predicted & ~truth) = 1;
errorClass(~predicted & truth) = 2;
errorClass(predicted & truth) = 3;
end

function writeGridCsv(map, outputPath)
pointCount = numel(map.Score);
ProblemId = repmat(map.ProblemId, pointCount, 1);
NormalizedX1 = map.UnitX1(:);
NormalizedX2 = map.UnitX2(:);
PhysicalX1 = map.PhysicalX1(:);
PhysicalX2 = map.PhysicalX2(:);
PofScore = map.Score(:);
RawGpMean = map.RawMean(:);
ExactFeasible = double(map.Truth(:));
PredictedFeasibleAtHalf = double(map.PredictedFeasible(:));
ErrorClass = map.ErrorClass(:);
LocalLengthScale = map.LocalLength(:);
gridTable = table( ...
    ProblemId, NormalizedX1, NormalizedX2, PhysicalX1, PhysicalX2, ...
    PofScore, RawGpMean, ExactFeasible, ...
    PredictedFeasibleAtHalf, ErrorClass, LocalLengthScale);
writetable(gridTable, outputPath);
end

function campaign = summarizeRun(definition, result, initialMetric, finalMetric)
selectionSource = string(result.data.selectionSource);
iterations = result.iterations;
fallbackCount = 0;
if ~isempty(iterations)
    fallbackCount = nnz([iterations.fallbackUsed]);
end
campaign = emptyCampaignRow();
campaign.ProblemId = definition.Id;
campaign.Status = string(result.meta.status);
campaign.InitialCount = definition.InitialCount;
campaign.SequentialBudget = definition.SequentialBudget;
campaign.TotalEvaluations = size(result.data.X, 1);
campaign.InitialSeed = definition.InitialSeed;
campaign.SolverSeed = definition.SolverSeed;
campaign.InitialFeasibleCount = initialMetric.FeasibleObserved;
campaign.FinalFeasibleCount = finalMetric.FeasibleObserved;
campaign.PrimarySelections = nnz(selectionSource == "primary");
campaign.ChallengerSelections = nnz(selectionSource == "challenger");
campaign.FallbackSelections = fallbackCount;
campaign.FinalParetoCount = result.pareto.nPoints;
campaign.FinalHypervolume = result.pareto.hypervolume;
campaign.FinalAUC = finalMetric.AUC;
campaign.FinalBrier = finalMetric.Brier;
campaign.FinalFalseFeasibleRate = finalMetric.FalseFeasibleRate;
campaign.FinalFalseInfeasibleRate = finalMetric.FalseInfeasibleRate;
campaign.FinalBalancedAccuracy = finalMetric.BalancedAccuracy;
campaign.WallTimeSeconds = result.meta.wallTimeSeconds;
end

function history = reconstructCossinHistory( ...
        definitions, runResults, unitGrid, U1, U2)
problemIds = ["COSSIN1", "COSSIN2"];
milestones = { [20, 30, 40, 50], [20, 40, 60, 80] };
maps = cell(2, 4);
rows = repmat(emptyMetricRow(), 0, 1);

for problemIndex = 1:2
    definitionIndex = find( ...
        string({definitions.Id}) == problemIds(problemIndex), 1);
    definition = definitions(definitionIndex);
    result = runResults{definitionIndex};
    problem = getBenchmarkProblem(definition.ProblemId);
    for milestoneIndex = 1:4
        prefixCount = milestones{problemIndex}(milestoneIndex);
        [map, metric] = evaluatePofField( ...
            problem, result, prefixCount, unitGrid, U1, U2, ...
            "learning");
        maps{problemIndex, milestoneIndex} = map;
        rows(end + 1, 1) = metric; %#ok<AGROW>
    end
end
history = struct( ...
    "ProblemIds", problemIds, ...
    "Milestones", {milestones}, ...
    "Maps", {maps}, ...
    "Metrics", struct2table(rows));
end

