function outputs = reproduce_two_dimensional_pof_results(varargin)
%REPRODUCE_TWO_DIMENSIONAL_POF_RESULTS Run and plot the 2-D PoF campaign.
%   OUTPUTS = REPRODUCE_TWO_DIMENSIONAL_POF_RESULTS() runs four deterministic
%   cTSEMO cases using the exact source currently shipped in this repository:
%
%     COSSIN1   20 initial + 30 sequential evaluations
%     COSSIN2   20 initial + 60 sequential evaluations
%     BNH       10 initial + 30 sequential evaluations
%     SRN       10 initial + 30 sequential evaluations
%
%   Every initial design includes the four corners. The solver uses the
%   current GA-primary policy: 1,024 scored reference designs seed a bounded
%   genetic algorithm with population size 80, while an independent 512-point
%   LHS challenger is evaluated by the same frozen acquisition. Each objective
%   draw uses 256 random Fourier features. Stable run records, independent-
%   grid PoF diagnostics, figures, and manifests are written under
%   manuscript/artifacts/two_dimensional_campaign.
%
%   REPRODUCE_TWO_DIMENSIONAL_POF_RESULTS("ReuseResults",true) skips the
%   optimizer and reconstructs all diagnostics from the existing stable
%   run records. This is useful for figure-only reproduction.
%
%   REPRODUCE_TWO_DIMENSIONAL_POF_RESULTS("ShowFigures",true) leaves the
%   generated figures visible. Figures are hidden by default so the script
%   does not switch or raise desktop windows.
%
%   Exact benchmark feasibility is used only on an offline 201-by-201
%   cell-centred grid for diagnostics. It is never supplied to the solver
%   except when evaluating a point selected for an expensive query.

parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ReuseResults", false, @isLogicalScalar);
addParameter(parser, "ShowFigures", false, @isLogicalScalar);
parse(parser, varargin{:});
settings = parser.Results;

studyDirectory = string(fileparts(mfilename("fullpath")));
repositoryRoot = string(fileparts(fileparts(studyDirectory)));
artifactRoot = fullfile(repositoryRoot, "manuscript", "artifacts", ...
    "two_dimensional_campaign");
runDirectory = fullfile(artifactRoot, "runs");
gridDirectory = fullfile(artifactRoot, "grids");
figureDirectory = fullfile(artifactRoot, "figures");
runtimeLogRoot = fullfile(tempdir, "ctsemo_two_dimensional_pof_logs");

verifyRepository(repositoryRoot);
ensureDirectory(artifactRoot);
ensureDirectory(runDirectory);
ensureDirectory(gridDirectory);
ensureDirectory(figureDirectory);
ensureDirectory(runtimeLogRoot);

previousPath = path;
restorePath = onCleanup(@() path(previousPath));
setup_ctsemo();

definitions = campaignDefinitions();
configurationTable = configurationAsTable(definitions);
writetable(configurationTable, fullfile(artifactRoot, "run_configuration.csv"));
writeSourceManifest(repositoryRoot, mfilename("fullpath"), artifactRoot);

if ~settings.ReuseResults
    runResults = runCampaign(definitions, runDirectory, runtimeLogRoot);
else
    runResults = loadStableResults(definitions, runDirectory);
end

gridSize = 201;
u = ((1:gridSize) - 0.5) ./ gridSize;
[U1, U2] = meshgrid(u, u);
unitGrid = [U1(:), U2(:)];

mapRecords = cell(numel(definitions), 1);
metricRows = repmat(emptyMetricRow(), 0, 1);
campaignRows = repmat(emptyCampaignRow(), numel(definitions), 1);

for caseIndex = 1:numel(definitions)
    definition = definitions(caseIndex);
    result = runResults{caseIndex};
    problem = getBenchmarkProblem(definition.ProblemId);
    validateCompletedResult(result, problem, definition);

    initialCount = definition.InitialCount;
    [~, initialMetric] = evaluatePofField( ...
        problem, result, initialCount, unitGrid, U1, U2, "initial");
    [finalMap, finalMetric] = evaluatePofField( ...
        problem, result, size(result.data.X, 1), ...
        unitGrid, U1, U2, "final");
    mapRecords{caseIndex} = finalMap;
    metricRows(end + 1, 1) = initialMetric; %#ok<AGROW>
    metricRows(end + 1, 1) = finalMetric; %#ok<AGROW>
    campaignRows(caseIndex) = summarizeRun( ...
        definition, result, initialMetric, finalMetric);

    writeGridCsv(finalMap, fullfile(gridDirectory, ...
        definition.Id + "_final_pof_grid.csv"));
end

metricsTable = struct2table(metricRows);
campaignTable = struct2table(campaignRows);
writetable(metricsTable, fullfile(artifactRoot, "pof_metrics.csv"));
writetable(campaignTable, fullfile(artifactRoot, "campaign_summary.csv"));

history = reconstructCossinHistory( ...
    definitions, runResults, unitGrid, U1, U2);
writetable(history.Metrics, fullfile(artifactRoot, ...
    "cossin_learning_metrics.csv"));

fieldDataPath = fullfile(artifactRoot, "pof_field_data.mat");
save(fieldDataPath, "mapRecords", "history", "u", "gridSize", "-v7.3");

visibility = "off";
if settings.ShowFigures
    visibility = "on";
end
figureRecords = makeCampaignFigures( ...
    mapRecords, definitions, history, figureDirectory, visibility);
figureManifest = struct2table(figureRecords);
writetable(figureManifest, fullfile(artifactRoot, "figure_manifest.csv"));

manifest = makeCampaignManifest( ...
    definitions, gridSize, campaignTable, metricsTable, figureManifest);
writeJson(fullfile(artifactRoot, "campaign_manifest.json"), manifest);
writeSummaryText(fullfile(artifactRoot, "SUMMARY.txt"), ...
    campaignTable, metricsTable);

artifactIndexDirectory = fileparts(artifactRoot);
addpath(artifactIndexDirectory);
update_artifact_manifest;

outputs = struct( ...
    "RepositoryRoot", repositoryRoot, ...
    "ArtifactRoot", artifactRoot, ...
    "CampaignSummary", campaignTable, ...
    "PofMetrics", metricsTable, ...
    "FigureManifest", figureManifest, ...
    "FieldData", fieldDataPath);

fprintf("Two-dimensional PoF campaign artifacts:\n  %s\n", artifactRoot);
disp(campaignTable(:, ["ProblemId", "TotalEvaluations", ...
    "FinalFeasibleCount", "FinalAUC", "FinalBrier"]));

clear restorePath
end

