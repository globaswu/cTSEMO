function rasterProgress(fraction, stage)
    persistent lastStage lastDecile
    if isempty(lastStage) || string(stage) ~= lastStage
        lastStage = string(stage);
        lastDecile = -1;
    end
    decile = floor(10 * fraction);
    if decile > lastDecile || fraction >= 1
        fprintf("WB raster %s: %.0f%%\n", stage, 100 * fraction);
        lastDecile = decile;
    end
end

