            definitions.SourceManifestHashFile(index);
        cases(index).sourceManifestSHA256 = lower( ...
            string(definitions.SourceManifestSHA256(index)));
        cases(index).problem = getBenchmarkProblem( ...
            definitions.ProblemId(index));
        cases(index).result = loaded.result;
        cases(index).designSeed = double(definitions.InitialSeed(index));
        cases(index).solverSeed = double(definitions.SolverSeed(index));
