function [value, root] = portablePathList(value, options, releaseRoot)
    value = string(value);
    root = "";
    if value == ""
        return
    end
    parts = split(value, "; ");
    roots = strings(size(parts));
    for index = 1:numel(parts)
        [parts(index), roots(index)] = portablePath( ...
            parts(index), options, releaseRoot);
    end
    value = strjoin(parts, "; ");
    roots = unique(roots(roots ~= ""), "stable");
    root = strjoin(roots, "; ");
end

function [value, root] = portablePath(value, options, releaseRoot)
    value = string(value);
    root = pathToken(value);
    if value == "" || root ~= ""
        return
    end
    if ~isAbsolutePath(value)
        return
    end

    [inside, relative] = pathRelativeTo(value, options.FigureDirectory);
    if inside
        root = "@FIGURE_ROOT@";
        value = tokenPath(root, relative);
        return
    end
    [inside, relative] = pathRelativeTo(value, options.DataDirectory);
    if inside
        root = "@DATA_ROOT@";
        value = tokenPath(root, relative);
        return
    end
    [inside, relative] = pathRelativeTo(value, releaseRoot);
    if inside
        root = "@RELEASE_ROOT@";
        value = tokenPath(root, relative);
        return
    end
    if options.RunCompetitorOverlay && ...
            options.CompetitorSummaryFile ~= ""
        competitorDirectory = fileparts(options.CompetitorSummaryFile);
        relative = relativePath(value, competitorDirectory);
        root = "@COMPETITOR_SUMMARY_DIR@";
        value = tokenPath(root, relative);
        return
    end
    error("cTSEMO:Diagnostics:UnportableArchivePath", ...
        "No declared archive path root covers: %s", value);
end

function token = pathToken(value)
    match = regexp(char(value), "^(@[^@]+@)", "tokens", "once");
    if isempty(match)
        token = "";
    else
        token = string(match{1});
    end
end

function value = tokenPath(token, relative)
    relative = replace(string(relative), "\", "/");
    if relative == "" || relative == "."
        value = token;
    else
        value = token + "/" + relative;
    end
end

function absolute = isAbsolutePath(value)
    absolute = ~isempty(regexp(char(value), ...
        "^(?:[A-Za-z]:[\\/]|[\\/]{2}|/)", "once"));
end

function [inside, relative] = pathRelativeTo(value, root)
    value = normalizedPath(value);
    root = normalizedPath(root);
    inside = strcmpi(value, root);
    relative = "";
    if inside
        return
    end
    prefix = root + "/";
    inside = startsWith(lower(value), lower(prefix));
    if inside
        relative = extractAfter(value, strlength(prefix));
    end
end

function relative = relativePath(value, root)
    valueParts = split(normalizedPath(value), "/");
    rootParts = split(normalizedPath(root), "/");
    common = 0;
    maximum = min(numel(valueParts), numel(rootParts));
    while common < maximum && ...
            strcmpi(valueParts(common + 1), rootParts(common + 1))
        common = common + 1;
    end
    if common == 0
        error("cTSEMO:Diagnostics:DifferentArchiveVolumes", ...
            "External source and competitor summary are on different roots.");
    end
    up = repmat("..", numel(rootParts) - common, 1);
    down = valueParts(common + 1:end);
    parts = [up; down];
    if isempty(parts)
        relative = ".";
    else
        relative = strjoin(parts, "/");
    end
end

function value = normalizedPath(value)
    value = replace(string(value), "\", "/");
    value = regexprep(value, "/+$", "");
end

