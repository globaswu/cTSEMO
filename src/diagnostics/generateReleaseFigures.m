function [feasibility, hypervolume, sourceCounts] = ...
        campaignHistories(cases)
    feasibility = table();
    hypervolume = table();
    sourceRows = table();

    for caseIndex = 1:numel(cases)
        item = cases(caseIndex);
        result = item.result;
        n = size(result.data.X, 1);
        evaluation = (1:n).';
        sequentialIteration = max(0, evaluation - result.data.nInitial);
        label = logical(result.data.isFeasible);
        cumulativeCount = cumsum(double(label));
        cumulativeRate = cumulativeCount ./ evaluation;
        caseColumn = repmat(item.key, n, 1);
        block = table( ...
            caseColumn, evaluation, sequentialIteration, label, ...
            cumulativeCount, cumulativeRate, ...
            'VariableNames', { ...
            'Case', 'Evaluation', 'SequentialIteration', 'IsFeasible', ...
            'CumulativeFeasibleCount', 'CumulativeFeasibleRate'});
        feasibility = [feasibility; block]; %#ok<AGROW>

        history = result.pareto.history;
        finalValue = history.hypervolume(end);
        if finalValue > 0
            normalized = history.hypervolume ./ finalValue;
        else
            normalized = NaN(size(history.hypervolume));
        end
        block = table( ...
            repmat(item.key, numel(history.iteration), 1), ...
            history.iteration, history.evaluationCount, ...
            history.hypervolume, normalized, history.feasibleCount, ...
            repmat(result.pareto.referencePoint(1), ...
            numel(history.iteration), 1), ...
            repmat(result.pareto.referencePoint(2), ...
            numel(history.iteration), 1), ...
            'VariableNames', { ...
            'Case', 'SequentialIteration', 'EvaluationCount', ...
            'FixedReferenceHypervolume', 'FractionOfRunFinalHypervolume', ...
            'FeasibleCount', 'ReferenceF1', 'ReferenceF2'});
        hypervolume = [hypervolume; block]; %#ok<AGROW>

        sources = string(result.data.selectionSource( ...
            result.data.nInitial + 1:end));
        names = unique(sources, "stable");
        for sourceIndex = 1:numel(names)
            block = table(item.key, names(sourceIndex), ...
                nnz(sources == names(sourceIndex)), ...
                'VariableNames', {'Case', 'SelectionSource', 'Count'});
            sourceRows = [sourceRows; block]; %#ok<AGROW>
        end
    end
    sourceCounts = sourceRows;
end

