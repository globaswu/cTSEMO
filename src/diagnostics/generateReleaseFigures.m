            double(definitions.PrimaryCandidateCount(index));
        cases(index).challengerCandidateCount = ...
            double(definitions.ChallengerCandidateCount(index));
        cases(index).objectiveFeatureCount = ...
            double(definitions.ObjectiveFeatureCount(index));
    end
end

function validateOfficialResult(result, definition, sourceFile)
    totalCount = size(result.data.X, 1);
    initialCount = result.data.nInitial;
    sequentialBudget = totalCount - initialCount;
    initialFeasible = nnz(result.data.isFeasible(1:initialCount));
    finalFeasible = nnz(result.data.isFeasible);
    observed = [ ...
        initialCount, sequentialBudget, totalCount, ...
        initialFeasible, finalFeasible];
    expected = [ ...
        definition.ExpectedInitialCount, ...
        definition.ExpectedSequentialBudget, ...
        definition.ExpectedTotalEvaluations, ...
        definition.ExpectedInitialFeasibleCount, ...
        definition.ExpectedFinalFeasibleCount];
    if ~isequal(double(observed), double(expected))
        error("cTSEMO:Diagnostics:CampaignSourceMismatch", ...
            "Stored counts do not match the source manifest: %s", ...
            sourceFile);
    end
    profile = [ ...
        result.options.candidates.primaryCount, ...
        result.options.challengers.count, ...
        result.options.objectiveGP.nFeatures];
    expectedProfile = [ ...
        definition.PrimaryCandidateCount, ...
        definition.ChallengerCandidateCount, ...
        definition.ObjectiveFeatureCount];
    if ~isequal(double(profile), double(expectedProfile))
        error("cTSEMO:Diagnostics:CampaignProfileMismatch", ...
            "Stored solver profile does not match the source manifest: %s", ...
            sourceFile);
    end
    if string(result.options.logging.level) ~= definition.LoggingLevel
        error("cTSEMO:Diagnostics:CampaignLoggingMismatch", ...
            "Stored logging level does not match the source manifest: %s", ...
            sourceFile);
    end
end

