function label = objectiveLabel(problem, index)
    name = string(problem.objectiveNames{index});
    unit = string(problem.objectiveUnits{index});
    if unit == ""
        label = name;
    else
        label = name + " (" + unit + ")";
    end
end

function [files, names, sourceTable] = ...
        weldedBeamCompetitorSources(summaryFile)
    summary = readtable(summaryFile, ...
        "TextType", "string", "VariableNamingRule", "preserve");
    requested = [ ...
        "BoTorch (150)"; "Trieste (150)"; "USeMOC (150)"; ...
        "COMBOO (150)"; "PAC-MOO (150)"];
    selected = ismember(summary.Solver, requested);
    sourceTable = summary(selected, [ ...
        "Solver", "Group", "EvaluationBudget", "Source"]);
    [~, order] = ismember(requested, sourceTable.Solver);
    if any(order == 0)
        error("cTSEMO:Diagnostics:MissingCompetitorSource", ...
            "The fixed welded-beam competitor source set is incomplete.");
    end
    sourceTable = sourceTable(order, :);
    sourceTable.InformationStatus = repmat( ...
        "continuous per-constraint margins", height(sourceTable), 1);
    sourceTable.ComparisonStatus = repmat( ...
        "unmatched exploratory overlay; no ranking", ...
        height(sourceTable), 1);
    files = string(sourceTable.Source);
    names = string(sourceTable.Solver);
    if any(~isfile(files))
        missing = files(~isfile(files));
        error("cTSEMO:Diagnostics:MissingCompetitorCsv", ...
            "Competitor CSV not found: %s", strjoin(missing, "; "));
    end
end

