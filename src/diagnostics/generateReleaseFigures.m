function manifest = generateReleaseFigures(options)
%GENERATERELEASEFIGURES Generate figures from a compatible v0.1 campaign.
%   MANIFEST = GENERATERELEASEFIGURES(CampaignRoot=PATH) reads the archived
%   campaign_sources.csv schema and writes its legacy diagnostic package.
%   Current manuscript figures use the entry points in docs/RESULTS_MAP.md.
%
%   The default welded-beam raster is exactly 50^4 cell-centered points.
%   Lower resolution is never substituted silently. Set RunWbRaster=false
%   only for a deliberate fast preflight.

    arguments
        options.CampaignRoot (1,1) string = ""
        options.FigureDirectory (1,1) string = ""
        options.DataDirectory (1,1) string = ""
        options.CompetitorSummaryFile (1,1) string = ""
        options.RunCompetitorOverlay (1,1) logical = false
        options.RunWbRaster (1,1) logical = true
        options.WbPointsPerDimension (1,1) double ...
            {mustBeInteger, mustBePositive} = 50
        options.WbChunkSize (1,1) double ...
            {mustBeInteger, mustBePositive} = 100000
        options.Resolution (1,1) double ...
            {mustBePositive, mustBeFinite} = 300
    end

    releaseRoot = fileparts(fileparts(mfilename("fullpath")));
    options = resolvePaths(options, releaseRoot);
    validateInputs(options);
    ensureDirectory(options.FigureDirectory);
    ensureDirectory(options.DataDirectory);

    previousPath = path;
    pathCleanup = onCleanup(@() path(previousPath));
    addpath(releaseRoot);
    addpath(fullfile(releaseRoot, "benchmarks"));
    addpath(fullfile(releaseRoot, "diagnostics"));

    definitions = campaignDefinitions(options.CampaignRoot, releaseRoot);
    fprintf("Loading %d shipped-profile campaign cases from %s\n", ...
        height(definitions), options.CampaignRoot);
    cases = loadCampaignCases(definitions);
    manifest = emptyManifest();
    captions = emptyCaptions();

    [summary, sourcePaths, optionsByCase] = campaignSummary(cases);
    sourcePaths = portableCampaignSourcePaths( ...
        sourcePaths, options, releaseRoot);
    optionsByCase = portableSolverOptions( ...
        optionsByCase, options, releaseRoot);
    summaryFile = fullfile(options.DataDirectory, ...
        "campaign_run_summary.csv");
    writetable(summary, summaryFile);
    manifest = addManifest(manifest, summaryFile, "data", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Measured campaign counts, hypervolume, selection, and timing summary.");

    sourceFile = fullfile(options.DataDirectory, ...
        "campaign_source_paths.csv");
    writetable(sourcePaths, sourceFile);
    manifest = addManifest(manifest, sourceFile, "provenance", ...
        options.CampaignRoot, ...
        "Exact campaign MAT-file and solver-output paths.");

    optionsMatFile = fullfile(options.DataDirectory, ...
        "campaign_solver_options.mat");
    save(optionsMatFile, "optionsByCase", "-v7");
    manifest = addManifest(manifest, optionsMatFile, "options", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Exact stored solver option structs for every case.");

    optionsJsonFile = fullfile(options.DataDirectory, ...
        "campaign_solver_options.json");
    writelines(jsonencode(optionsByCase, "PrettyPrint", true), ...
        optionsJsonFile);
    manifest = addManifest(manifest, optionsJsonFile, "options", ...
        optionsMatFile, "Human-readable serialization of stored options.");

    fprintf("Generating COSSIN2 final-iteration atlas.\n");
    cossin2 = caseByKey(cases, "COSSIN2");
    [atlasFigure, atlasMetadata] = plot2DIterationAtlas( ...
        cossin2.result, numel(cossin2.result.iterations), ...
        "Problem", cossin2.problem, ...
        "Title", "COSSIN2 final iteration: sampled acquisition decomposition");
    [atlasPng, atlasPdf] = exportFigurePair( ...
        atlasFigure, options.FigureDirectory, ...
        "fig_v4_cossin2_final_iteration_atlas", options.Resolution);
    close(atlasFigure);
    manifest = addFigurePair(manifest, atlasPng, atlasPdf, ...
        cossin2.sourceFile, atlasMetadata.caption);
    captions = addCaption(captions, atlasPng, ...
        atlasMetadata.caption, atlasMetadata.source);

    fprintf("Evaluating COSSIN2 post-run PoF on an independent grid.\n");
    [cossin2Model, cossin2FitDiagnostics] = ...
        fitFinalPofModel(cossin2.result);
    [cossin2ProbeX, cossin2ProbeUnit] = ...
        twoDimensionalCellCenters(cossin2.problem, 201);
    [cossin2Pof, cossin2Raw] = ctsemo.predictClippedBinaryPof( ...
        cossin2Model, cossin2ProbeUnit);
    cossin2Truth = logical(cossin2.problem.feasible(cossin2ProbeX));
    [validationFigure, validationMetrics, validationMetadata] = ...
        plotPofValidation(cossin2.result, ...
        "Score", cossin2Pof, ...
        "Truth", cossin2Truth, ...
        "Points", cossin2ProbeX, ...
        "Problem", cossin2.problem, ...
        "SampleDescription", ...
        "Independent uniform 201-by-201 cell-centered domain grid", ...
        "Title", "COSSIN2 post-run clipped-PoF validation");
    [validationPng, validationPdf] = exportFigurePair( ...
        validationFigure, options.FigureDirectory, ...
        "fig_v4_cossin2_pof_validation", options.Resolution);
    close(validationFigure);
    manifest = addFigurePair(manifest, validationPng, validationPdf, ...
        cossin2.sourceFile, validationMetadata.caption);
    captions = addCaption(captions, validationPng, ...
        validationMetadata.caption, cossin2.sourceFile);

    cossin2ProbeTable = table( ...
        cossin2ProbeX(:, 1), cossin2ProbeX(:, 2), ...
        cossin2Raw, cossin2Pof, cossin2Truth, ...
        'VariableNames', { ...
        'x1', 'x2', 'RawMean', 'p_i', 'IsFeasible'});
    cossin2ProbeFile = fullfile(options.DataDirectory, ...
        "cossin2_independent_grid_pof.csv");
    writetable(cossin2ProbeTable, cossin2ProbeFile);
    manifest = addManifest(manifest, cossin2ProbeFile, "data", ...
        cossin2.sourceFile, ...
        "Independent cell-centered probe coordinates, raw mean, p_i, and truth.");
    pofModelFile = fullfile(options.DataDirectory, ...
        "cossin2_postrun_pof_model.mat");
    [sourceFilePath, ~] = portablePath( ...
        cossin2.sourceFile, options, releaseRoot);
    save(pofModelFile, "cossin2Model", ...
        "cossin2FitDiagnostics", "sourceFilePath", "-v7");
    manifest = addManifest(manifest, pofModelFile, "model", ...
        cossin2.sourceFile, ...
        "PoF model refitted to all 80 stored binary labels.");
    [pofArtifacts, pofManifest] = writePofMetricArtifacts( ...
        validationMetrics, options.DataDirectory, "cossin2");
    manifest = [manifest; pofManifest];

    fprintf("Generating campaign history tables and combined history figure.\n");
    [feasibilityHistory, hypervolumeHistory, selectionCounts] = ...
        campaignHistories(cases);
    feasibilityFile = fullfile(options.DataDirectory, ...
        "campaign_feasibility_history.csv");
    hypervolumeFile = fullfile(options.DataDirectory, ...
        "campaign_fixed_reference_hypervolume_history.csv");
    selectionFile = fullfile(options.DataDirectory, ...
        "campaign_selection_source_counts.csv");
    writetable(feasibilityHistory, feasibilityFile);
    writetable(hypervolumeHistory, hypervolumeFile);
    writetable(selectionCounts, selectionFile);
    manifest = addManifest(manifest, feasibilityFile, "data", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Per-evaluation binary feasibility and cumulative rates.");
    manifest = addManifest(manifest, hypervolumeFile, "data", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Stored fixed-reference within-run hypervolume histories.");
    manifest = addManifest(manifest, selectionFile, "data", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Logged source counts excluding initial designs.");

    [historyFigure, historyCaption] = plotCampaignHistories( ...
        cases, feasibilityHistory, hypervolumeHistory, selectionCounts);
    [historyPng, historyPdf] = exportFigurePair( ...
        historyFigure, options.FigureDirectory, ...
        "fig_v4_campaign_histories", options.Resolution);
    close(historyFigure);
    manifest = addFigurePair(manifest, historyPng, historyPdf, ...
        strjoin(sourcePaths.SourceFile, "; "), historyCaption);
    captions = addCaption(captions, historyPng, ...
        historyCaption, strjoin(sourcePaths.SourceFile, "; "));

    fprintf("Generating BNH zero-initial-feasibility recovery timeline.\n");
    bnhStress = caseByKey(cases, "BNH_ALLINFEAS");
    [recoveryFigure, recoveryTable, recoveryCaption] = ...
        plotRecoveryTimeline(bnhStress);
    [recoveryPng, recoveryPdf] = exportFigurePair( ...
        recoveryFigure, options.FigureDirectory, ...
        "fig_v4_bnh_zero_initial_feasibility_recovery", ...
        options.Resolution);
    close(recoveryFigure);
    recoveryFile = fullfile(options.DataDirectory, ...
        "bnh_zero_initial_feasibility_recovery.csv");
    writetable(recoveryTable, recoveryFile);
    manifest = addFigurePair(manifest, recoveryPng, recoveryPdf, ...
        bnhStress.sourceFile, recoveryCaption);
    manifest = addManifest(manifest, recoveryFile, "data", ...
        bnhStress.sourceFile, ...
        "Iteration-level recovery state, source, reason, and observed label.");
    captions = addCaption(captions, recoveryPng, ...
        recoveryCaption, bnhStress.sourceFile);

    fprintf("Generating final Pareto panels across the core campaign.\n");
    [paretoFigure, paretoSummary, paretoCaption] = ...
        plotCampaignParetoPanels(cases);
    [paretoPng, paretoPdf] = exportFigurePair( ...
        paretoFigure, options.FigureDirectory, ...
        "fig_v4_campaign_final_pareto_panels", options.Resolution);
    close(paretoFigure);
    paretoFile = fullfile(options.DataDirectory, ...
        "campaign_final_pareto_summary.csv");
    writetable(paretoSummary, paretoFile);
    manifest = addFigurePair(manifest, paretoPng, paretoPdf, ...
        strjoin(sourcePaths.SourceFile, "; "), paretoCaption);
    manifest = addManifest(manifest, paretoFile, "data", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Measured final feasible and nondominated point counts.");
    captions = addCaption(captions, paretoPng, ...
        paretoCaption, strjoin(sourcePaths.SourceFile, "; "));

    weldedBeam = caseByKey(cases, "WELDEDBEAM");
    if options.RunCompetitorOverlay
        fprintf( ...
            "Generating unmatched welded-beam competitor pilot overlay.\n");
        [competitorFiles, competitorNames, competitorSourceTable] = ...
            weldedBeamCompetitorSources(options.CompetitorSummaryFile);
        unequalInformationNote = ...
            "Unmatched pilot: existing competitor runs received continuous " + ...
            "per-constraint margins, whereas this shipped cTSEMO run received " + ...
            "one aggregate binary label. Initial designs, seeds, and " + ...
            "implementations are not matched; no ranking is performed.";
        [competitorFigure, competitorMetrics, competitorMetadata] = ...
            plotWeldedBeamPilotComparison( ...
            weldedBeam.result, competitorFiles, ...
            "Names", competitorNames, ...
            "ObjectiveColumns", ["f1", "f2"], ...
            "Problem", weldedBeam.problem, ...
            "ComparisonNote", unequalInformationNote);
        [competitorPng, competitorPdf] = exportFigurePair( ...
            competitorFigure, options.FigureDirectory, ...
            "fig_v4_weldedbeam_unmatched_competitor_overlay", ...
            options.Resolution);
        close(competitorFigure);
        competitorSourceFile = fullfile(options.DataDirectory, ...
            "weldedbeam_unmatched_competitor_sources.csv");
        competitorSourceTable = portableCompetitorFileTable( ...
            competitorSourceTable, options, releaseRoot);
        writetable(competitorSourceTable, competitorSourceFile);
        manifest = addFigurePair(manifest, competitorPng, competitorPdf, ...
            strjoin([weldedBeam.sourceFile; competitorFiles], "; "), ...
            competitorMetadata.caption);
        manifest = addManifest(manifest, ...
            competitorSourceFile, "provenance", ...
            options.CompetitorSummaryFile, ...
            "Explicit competitor CSV paths and unequal-information status.");
        captions = addCaption(captions, competitorPng, ...
            competitorMetadata.caption, ...
            strjoin([weldedBeam.sourceFile; competitorFiles], "; "));
        competitorMetricsFile = fullfile(options.DataDirectory, ...
            "weldedbeam_unmatched_competitor_file_metrics.csv");
        competitorFileMetrics = portableCompetitorFileTable( ...
            competitorMetrics.competitorFiles, options, releaseRoot);
        writetable(competitorFileMetrics, competitorMetricsFile);
        manifest = addManifest(manifest, competitorMetricsFile, "data", ...
            options.CompetitorSummaryFile, ...
            "Rows and objective columns loaded for the unmatched overlay.");
    else
        fprintf("Skipping competitor overlay by explicit default.\n");
    end

    if options.RunWbRaster
        if options.WbPointsPerDimension ~= 50
            warning("cTSEMO:Diagnostics:NoncanonicalRasterResolution", ...
                "RunWbRaster is enabled with %d rather than the " + ...
                "canonical 50 points per dimension.", ...
                options.WbPointsPerDimension);
        end
        fprintf("Computing welded-beam %d^4 cell-centered PoF raster.\n", ...
            options.WbPointsPerDimension);
        rasterFile = fullfile(options.DataDirectory, ...
            "weldedbeam_sorted_pof_raster_50x4.mat");
        weldedBeamRaster = computeSortedPofRaster4D( ...
            weldedBeam.result, weldedBeam.problem, ...
            "PointsPerDimension", options.WbPointsPerDimension, ...
            "ChunkSize", options.WbChunkSize, ...
            "GridPlacement", "cellCenters", ...
            "UseFinalData", true, ...
            "Threshold", 0.5, ...
            "OutputFile", rasterFile, ...
            "ProgressFunction", @rasterProgress);
        manifest = addManifest(manifest, rasterFile, "data", ...
            weldedBeam.sourceFile, ...
            "Exact 4D score/truth/error rank raster with trace indices.");

        [rasterFigure, rasterMetadata] = ...
            plotSortedPofRaster4D(weldedBeamRaster, ...
            "Title", ...
            "Welded beam: 50^4 cell-centered clipped-PoF rank diagnostic");
        [rasterPng, rasterPdf] = exportFigurePair( ...
            rasterFigure, options.FigureDirectory, ...
            "fig_v4_weldedbeam_sorted_pof_raster_50x4", ...
            options.Resolution);
        close(rasterFigure);
        manifest = addFigurePair(manifest, rasterPng, rasterPdf, ...
            weldedBeam.sourceFile, rasterMetadata.caption);
        captions = addCaption(captions, rasterPng, ...
            rasterMetadata.caption, weldedBeam.sourceFile);

        fprintf("Computing welded-beam 50^4 PoF validation metrics.\n");
        [wbValidationFigure, wbValidationMetrics, wbValidationMetadata] = ...
            plotPofValidation(weldedBeam.result, ...
            "Score", weldedBeamRaster.score(:), ...
            "Truth", weldedBeamRaster.truth(:), ...
            "Threshold", weldedBeamRaster.threshold, ...
            "MaxCurvePoints", 6000, ...
            "SampleDescription", ...
            "Uniform 50^4 cell-centered welded-beam tensor grid", ...
            "Title", ...
            "Welded beam: clipped-PoF validation on 6,250,000 points");
        [wbValidationPng, wbValidationPdf] = exportFigurePair( ...
            wbValidationFigure, options.FigureDirectory, ...
            "fig_v4_weldedbeam_pof_validation_50x4", ...
            options.Resolution);
        close(wbValidationFigure);
        manifest = addFigurePair(manifest, ...
            wbValidationPng, wbValidationPdf, weldedBeam.sourceFile, ...
            wbValidationMetadata.caption);
        captions = addCaption(captions, wbValidationPng, ...
            wbValidationMetadata.caption, weldedBeam.sourceFile);

        [wbPofArtifacts, wbPofManifest] = writePofMetricArtifacts( ...
            wbValidationMetrics, options.DataDirectory, "weldedbeam_50x4");
        manifest = [manifest; wbPofManifest];
        rasterSummary = makeRasterSummary(weldedBeamRaster);
        rasterSummaryFile = fullfile(options.DataDirectory, ...
            "weldedbeam_sorted_pof_raster_summary.csv");
        writetable(rasterSummary, rasterSummaryFile);
        manifest = addManifest(manifest, rasterSummaryFile, "data", ...
            rasterFile, ...
            "Score distribution, truth volume, and threshold-error counts.");
    else
        fprintf("Skipping welded-beam 50^4 raster by explicit RunWbRaster=false.\n");
        wbPofArtifacts = strings(0, 1);
    end

    pathRoots = archivePathRoots(options);
    pathRootsFile = fullfile(options.DataDirectory, ...
        "archive_path_roots.csv");
    writetable(pathRoots, pathRootsFile);
    manifest = addManifest(manifest, pathRootsFile, "provenance", ...
        "Archive token declarations.", ...
        "Declared roots used by every portable path field.");

    captions = portableCaptionTable(captions, options, releaseRoot);
    captionsFile = fullfile(options.DataDirectory, ...
        "release_figure_captions_and_sources.csv");
    writetable(captions, captionsFile);
    manifest = addManifest(manifest, captionsFile, "provenance", ...
        strjoin(sourcePaths.SourceFile, "; "), ...
        "Cautious captions and exact source paths for generated figures.");

    manifestFile = fullfile(options.DataDirectory, ...
        "release_figure_manifest.csv");
    manifest = portableManifestTable(manifest, options, releaseRoot);
    writetable(manifest, manifestFile);
    pofArtifacts = portablePathVector( ...
        pofArtifacts, options, releaseRoot);
    wbPofArtifacts = portablePathVector( ...
        wbPofArtifacts, options, releaseRoot);
    generationOptions = portableGenerationOptions( ...
        options, releaseRoot);
    save(fullfile(options.DataDirectory, ...
        "release_generation_manifest.mat"), ...
        "manifest", "summary", "sourcePaths", ...
        "feasibilityHistory", "hypervolumeHistory", ...
        "selectionCounts", "paretoSummary", "pofArtifacts", ...
        "wbPofArtifacts", "generationOptions", "-v7");
    fprintf("Generated %d figure/data artifacts. Manifest: %s\n", ...
        height(manifest), manifestFile);

    clear pathCleanup
end

function options = resolvePaths(options, releaseRoot)
    if options.CampaignRoot == ""
        error("cTSEMO:Diagnostics:CampaignRootRequired", ...
            ["CampaignRoot is required for the archived v0.1 schema. " ...
             "See docs/RESULTS_MAP.md for current manuscript figures."]);
    end
    if options.FigureDirectory == ""
        options.FigureDirectory = fullfile( ...
            releaseRoot, "diagnostic-artifacts", "chap3-v4", "figures");
    end
    if options.DataDirectory == ""
        options.DataDirectory = fullfile( ...
            releaseRoot, "diagnostic-artifacts", "chap3-v4", "data");
    end
end

function validateInputs(options)
    if ~isfolder(options.CampaignRoot)
        error("cTSEMO:Diagnostics:MissingCampaignRoot", ...
            "Campaign root not found: %s", options.CampaignRoot);
    end
    sourceManifest = fullfile( ...
        options.CampaignRoot, "campaign_sources.csv");
    if ~isfile(sourceManifest)
        error("cTSEMO:Diagnostics:MissingCampaignSourceManifest", ...
            "Campaign source manifest not found: %s", sourceManifest);
    end
    if options.RunCompetitorOverlay && ...
            ~isfile(options.CompetitorSummaryFile)
        error("cTSEMO:Diagnostics:MissingCompetitorSummary", ...
            "RunCompetitorOverlay=true requires an explicit existing " + ...
            "CompetitorSummaryFile. Not found: %s", ...
            options.CompetitorSummaryFile);
    end
    if options.WbPointsPerDimension < 2
        error("cTSEMO:Diagnostics:RasterResolution", ...
            "WbPointsPerDimension must be at least two.");
    end
end

function ensureDirectory(directory)
    if isfolder(directory)
        return
    end
    [created, message] = mkdir(directory);
    if ~created
        error("cTSEMO:Diagnostics:DirectoryCreation", ...
            "Could not create directory '%s': %s", directory, message);
    end
end

function definitions = campaignDefinitions(campaignRoot, releaseRoot)
    sourceManifest = fullfile(campaignRoot, "campaign_sources.csv");
    definitions = readtable(sourceManifest, ...
        "TextType", "string", "VariableNamingRule", "preserve");
    required = [ ...
        "Key", "OfficialCaseId", "ProblemId", "DisplayName", ...
        "ResultFile", "CampaignSummaryFile", "CampaignManifestFile", ...
        "SourceManifestFile", "SourceManifestHashFile", ...
        "SourceManifestSHA256", ...
        "InitialSeed", "SolverSeed", "WallTimeSeconds", ...
        "LoggingLevel", "PrimaryCandidateCount", ...
        "ChallengerCandidateCount", "ObjectiveFeatureCount", ...
        "ExpectedInitialCount", "ExpectedSequentialBudget", ...
        "ExpectedTotalEvaluations", "ExpectedInitialFeasibleCount", ...
        "ExpectedFinalFeasibleCount"];
    if ~all(ismember(required, string(definitions.Properties.VariableNames)))
        error("cTSEMO:Diagnostics:InvalidCampaignSourceManifest", ...
            "The shipped-profile source manifest is missing required columns.");
    end
    definitions.ResultFile = makeAbsolutePaths( ...
        definitions.ResultFile, releaseRoot);
    definitions.CampaignSummaryFile = makeAbsolutePaths( ...
        definitions.CampaignSummaryFile, releaseRoot);
    definitions.CampaignManifestFile = makeAbsolutePaths( ...
        definitions.CampaignManifestFile, releaseRoot);
    definitions.SourceManifestFile = makeAbsolutePaths( ...
        definitions.SourceManifestFile, releaseRoot);
    definitions.SourceManifestHashFile = makeAbsolutePaths( ...
        definitions.SourceManifestHashFile, releaseRoot);
    if height(definitions) ~= 7 || numel(unique(definitions.Key)) ~= 7
        error("cTSEMO:Diagnostics:InvalidCampaignSourceSet", ...
            "Exactly seven uniquely keyed shipped-profile cases are required.");
    end
    if any(definitions.PrimaryCandidateCount ~= 1024) || ...
            any(definitions.ChallengerCandidateCount ~= 512) || ...
            any(definitions.ObjectiveFeatureCount ~= 256)
        error("cTSEMO:Diagnostics:WrongCampaignProfile", ...
            "Headline diagnostics require the shipped 1024/512/256 profile.");
    end
    if any(~isfile(definitions.ResultFile)) || ...
            any(~isfile(definitions.CampaignSummaryFile)) || ...
            any(~isfile(definitions.CampaignManifestFile)) || ...
            any(~isfile(definitions.SourceManifestFile)) || ...
            any(~isfile(definitions.SourceManifestHashFile))
        error("cTSEMO:Diagnostics:MissingCampaignSource", ...
            "At least one official result or campaign-authority file is missing.");
    end
    validateCampaignAuthority(definitions);
end

function validateCampaignAuthority(definitions)
    expectedHashes = lower(string(definitions.SourceManifestSHA256));
    if numel(unique(expectedHashes)) ~= 1 || ...
            isempty(regexp(char(expectedHashes(1)), ...
            "^[0-9a-f]{64}$", "once"))
        error("cTSEMO:Diagnostics:InvalidSourceManifestHash", ...
            "The source mapping must contain one valid SHA-256 authority.");
    end
    expectedHash = expectedHashes(1);
    hashFiles = unique(string(definitions.SourceManifestHashFile));
    manifestFiles = unique(string(definitions.CampaignManifestFile));
    sourceFiles = unique(string(definitions.SourceManifestFile));
    if numel(hashFiles) ~= 1 || numel(manifestFiles) ~= 1 || ...
            numel(sourceFiles) ~= 1
        error("cTSEMO:Diagnostics:MixedCampaignAuthority", ...
            "All diagnostic cases must share one sealed campaign authority.");
    end

    hashText = strtrim(fileread(hashFiles(1)));
    recordedHash = regexp(hashText, "^[0-9A-Fa-f]{64}", ...
        "match", "once");
    if isempty(recordedHash) || lower(string(recordedHash)) ~= expectedHash
        error("cTSEMO:Diagnostics:SourceManifestHashMismatch", ...
            "The declared digest does not match the campaign SHA-256 file.");
    end

    authority = jsondecode(fileread(manifestFiles(1)));
    if ~isfield(authority, "campaign") || ...
            string(authority.campaign.Status) ~= "completed" || ...
            lower(string(authority.campaign.SourceManifestSHA256)) ~= ...
            expectedHash
        error("cTSEMO:Diagnostics:CampaignAuthorityMismatch", ...
            "The campaign manifest is incomplete or has a different digest.");
    end
end

function paths = makeAbsolutePaths(paths, baseDirectory)
    paths = string(paths);
    for index = 1:numel(paths)
        value = paths(index);
        absolute = ~isempty(regexp(char(value), ...
            "^(?:[A-Za-z]:[\\/]|[\\/]{2}|/)", "once"));
        if ~absolute
            paths(index) = fullfile(baseDirectory, value);
        end
    end
end

function paths = portableCampaignSourcePaths( ...
        paths, options, releaseRoot)
    [paths.SourceFile, paths.SourceFilePathRoot] = ...
        portablePathVector(paths.SourceFile, options, releaseRoot);
    [paths.OfficialCampaignSummaryFile, ...
        paths.OfficialCampaignSummaryPathRoot] = portablePathVector( ...
        paths.OfficialCampaignSummaryFile, options, releaseRoot);
    [paths.OfficialCampaignManifestFile, ...
        paths.OfficialCampaignManifestPathRoot] = portablePathVector( ...
        paths.OfficialCampaignManifestFile, options, releaseRoot);
    [paths.OfficialReleaseSourceManifestFile, ...
        paths.OfficialReleaseSourceManifestPathRoot] = portablePathVector( ...
        paths.OfficialReleaseSourceManifestFile, options, releaseRoot);
    [paths.OfficialReleaseSourceManifestHashFile, ...
        paths.OfficialReleaseSourceManifestHashPathRoot] = ...
        portablePathVector( ...
        paths.OfficialReleaseSourceManifestHashFile, options, releaseRoot);
    [paths.SolverOutputDirectory, paths.SolverOutputPathRoot] = ...
        portablePathVector( ...
        paths.SolverOutputDirectory, options, releaseRoot);
end

function optionsByCase = portableSolverOptions( ...
        optionsByCase, generationOptions, releaseRoot)
    names = string(fieldnames(optionsByCase));
    for index = 1:numel(names)
        name = names(index);
        item = optionsByCase.(name);
        if isfield(item, "logging") && ...
                isfield(item.logging, "directory")
            [item.logging.directory, item.logging.directoryPathRoot] = ...
                portablePath( ...
                item.logging.directory, generationOptions, releaseRoot);
        end
        optionsByCase.(name) = item;
    end
end

function tableOut = portableCompetitorFileTable( ...
        tableIn, options, releaseRoot)
    tableOut = tableIn;
    names = string(tableOut.Properties.VariableNames);
    if ismember("Source", names)
        [tableOut.Source, tableOut.SourcePathRoot] = ...
            portablePathVector(tableOut.Source, options, releaseRoot);
    end
    if ismember("File", names)
