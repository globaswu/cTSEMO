function [model, diagnostics] = fitFinalPofModel(result)
    XUnit = (result.data.X - result.problem.lowerBound) ./ ...
        (result.problem.upperBound - result.problem.lowerBound);
    if all(result.data.isFeasible)
        model = struct( ...
            "construction", "constant_all_feasible", ...
            "dimension", size(XUnit, 2), ...
            "rawValue", result.options.pof.rawFeasible, ...
            "clippedValue", 1);
        diagnostics = struct( ...
            "construction", model.construction, ...
            "observationCount", size(XUnit, 1));
    else
        [model, diagnostics] = ctsemo.fitClippedBinaryPof( ...
            XUnit, result.data.isFeasible, result.options);
    end
end

function [X, XUnit] = twoDimensionalCellCenters(problem, gridCount)
    centers = ((1:gridCount) - 0.5) ./ gridCount;
    [u1, u2] = meshgrid(centers, centers);
    XUnit = [u1(:), u2(:)];
    X = problem.lowerBound + XUnit .* ...
        (problem.upperBound - problem.lowerBound);
end

