function [F, G] = c2dtlz2_reference(X)
%C2DTLZ2_REFERENCE Preserve the project benchmark equation in one function.
%   Extracted from the local functions c2dtlz2Objective and
%   c2dtlz2Constraint in the July 2026 project benchmark-suite script.

numberOfObjectives = 2;
g = sum((X(:, numberOfObjectives:end) - 0.5).^2, 2);
F = repmat(1 + g, 1, numberOfObjectives) .* ...
    fliplr(cumprod([ones(size(g, 1), 1), ...
    cos(X(:, 1:numberOfObjectives-1) .* pi ./ 2)], 2)) .* ...
    [ones(size(g, 1), 1), ...
    sin(X(:, numberOfObjectives-1:-1:1) .* pi ./ 2)];

radius = 0.5;
G = min(min((F - 1).^2 + ...
    repmat(sum(F.^2, 2), 1, numberOfObjectives) - ...
    F.^2 - radius.^2, [], 2), ...
    sum((F - 1 ./ sqrt(numberOfObjectives)).^2, 2) - radius.^2);
end
