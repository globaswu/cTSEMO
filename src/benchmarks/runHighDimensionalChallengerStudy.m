function [summary, aggregate, studyDirectory] = ...
        runHighDimensionalChallengerStudy(settings)
%RUNHIGHDIMENSIONALCHALLENGERSTUDY Paired D>=6 cTSEMO engineering study.
%   [SUMMARY, AGGREGATE, DIRECTORY] =
%   RUNHIGHDIMENSIONALCHALLENGERSTUDY() compares the legacy primary-only
%   Pareto filtering policy against complete-pool acquisition scoring on
%   four repository-traced constrained, two-objective problems.
%
%   This is an engineering screen, not a claim of solver superiority.
%   Initial designs, solver seeds, budgets, candidate counts, objective
%   features, feasibility-field settings, and independent validation probes
%   are paired between policies. Initial designs exclude the 2^D corners.
%
%   SETTINGS is a scalar struct with optional fields:
%     ProblemIds         default four registered D>=6 cases
%     Replicates         default 1:3
%     SequentialBudget   default 60
%     ProbeCount         default 65536
%     OutputRoot         default benchmarks/results
%     ContinueOnFailure  default true
%
%   The study writes per-run result MAT files, fixed-reference hypervolume
%   histories, global PoF diagnostics, paired differences, aggregate tables,
%   and noninteractive PNG figures.

if nargin < 1 || isempty(settings)
    settings = struct();
end
settings = resolveSettings(settings);

benchmarkRoot = fileparts(mfilename("fullpath"));
releaseRoot = fileparts(benchmarkRoot);
addpath(releaseRoot, benchmarkRoot);

studyId = "high_dimensional_challenger_study_" + ...
    string(datetime("now", "Format", "yyyyMMdd_HHmmss_SSS"));
studyDirectory = string(fullfile(settings.OutputRoot, studyId));
createDirectory(studyDirectory);
createDirectory(fullfile(studyDirectory, "runs"));

profiles = ["legacy_primary_filter", "complete_pool"];
problemIds = string(settings.ProblemIds(:)).';
replicates = reshape(double(settings.Replicates), 1, []);
totalRuns = numel(profiles) .* numel(problemIds) .* numel(replicates);
rows = repmat(emptyRunRow(), totalRuns, 1);
histories = repmat(emptyHistory(), totalRuns, 1);
rowIndex = 0;

manifest = struct( ...
    "StudyId", studyId, ...
    "CreatedAt", string(datetime("now", "TimeZone", "local")), ...
    "MatlabRelease", string(version("-release")), ...
    "ProblemIds", problemIds, ...
    "Profiles", profiles, ...
    "Replicates", replicates, ...
    "SequentialBudget", settings.SequentialBudget, ...
    "ProbeCount", settings.ProbeCount, ...
    "PrimaryCandidateCount", 1024, ...
    "ChallengerCandidateCount", 512, ...
    "ObjectiveFeatureCount", 256, ...
    "InitialDesign", ...
        "Deterministic randomized LHS; hyperrectangle corners excluded.", ...
    "PoF", ...
        "Shipped clipped locally variable-length GP mean; targets -0.25/1.25.", ...
    "PolicyDifference", ...
        "Only challengers.scoreCompletePools differs between paired arms.", ...
    "EvidenceClass", ...
        "Limited-budget, three-seed engineering screen; not journal-grade.");
writeJson(fullfile(studyDirectory, "study_manifest.json"), manifest);

for problemIndex = 1:numel(problemIds)
    problem = getBenchmarkProblem(problemIds(problemIndex));
    initialCount = initialCountForProblem(problem.id);
    probeSeed = 2026072800 + problemIndex;
    probeOptions = struct("IncludeCorners", false);
    probeX = initialDesign( ...
        problem, settings.ProbeCount, probeSeed, probeOptions);
    probeUnit = normalizeToUnit( ...
        probeX, problem.lowerBound, problem.upperBound);
    probeTruth = logical(problem.feasible(probeX));

    for replicate = replicates
        initialSeed = 2026072600 + 100 .* problemIndex + replicate;
        solverSeed = 2026072700 + 100 .* problemIndex + replicate;
        [X0, initialInfo] = initialDesign( ...
            problem, initialCount, initialSeed, ...
            struct("IncludeCorners", false));
        Y0 = problem.objective(X0);
        C0 = problem.label01(X0);

        for profileIndex = 1:numel(profiles)
            profile = profiles(profileIndex);
            rowIndex = rowIndex + 1;
            rows(rowIndex) = emptyRunRow();
            histories(rowIndex) = emptyHistory();
            runKey = sprintf("%s_rep%02d_%s", ...
                problem.id, replicate, profile);
            runRoot = fullfile(studyDirectory, "runs", runKey);
            createDirectory(runRoot);

            rows(rowIndex).ProblemId = string(problem.id);
            rows(rowIndex).Dimension = problem.dimension;
            rows(rowIndex).Profile = profile;
            rows(rowIndex).Replicate = replicate;
            rows(rowIndex).InitialSeed = initialSeed;
            rows(rowIndex).SolverSeed = solverSeed;
            rows(rowIndex).ProbeSeed = probeSeed;
            rows(rowIndex).InitialCount = initialCount;
            rows(rowIndex).SequentialBudget = ...
                settings.SequentialBudget;
            rows(rowIndex).InitialFeasibleCount = ...
                initialInfo.FeasibleCount;
            rows(rowIndex).ProbeCount = settings.ProbeCount;
            rows(rowIndex).ProbeFeasibleRate = mean(probeTruth);

            scoreCompletePools = profile == "complete_pool";
            overrides = struct( ...
                "maxEvaluations", settings.SequentialBudget, ...
                "seed", solverSeed, ...
                "feasibility", struct( ...
                    "inputEncoding", "feasibleIsOne"), ...
                "candidates", struct( ...
                    "primaryCount", 1024, ...
                    "includeCorners", false), ...
                "objectiveGP", struct("nFeatures", 256), ...
                "challengers", struct( ...
                    "enabled", true, ...
                    "count", 512, ...
                    "scoreCompletePools", scoreCompletePools), ...
                "logging", struct( ...
                    "level", "summary", ...
                    "directory", string(runRoot), ...
                    "checkpoint", false, ...
                    "saveEveryIteration", false));
            options = cTSEMOOptions(overrides);

            try
                result = cTSEMO( ...
                    problem.objective, problem.label01, ...
                    X0, Y0, C0, ...
                    problem.lowerBound, problem.upperBound, options);
                [rows(rowIndex), histories(rowIndex)] = summarizeRun( ...
                    rows(rowIndex), result, problem, probeUnit, ...
                    probeTruth, profile);
                rows(rowIndex).Status = "completed";
                rows(rowIndex).ResultDirectory = ...
                    string(result.meta.outputDirectory);
                saveRunDiagnostics( ...
                    result.meta.outputDirectory, histories(rowIndex), ...
                    rows(rowIndex));
            catch exception
                rows(rowIndex).Status = "failed";
                rows(rowIndex).ErrorIdentifier = ...
                    string(exception.identifier);
                rows(rowIndex).ErrorMessage = string(exception.message);
                if ~settings.ContinueOnFailure
                    saveCheckpoint( ...
                        studyDirectory, rows(1:rowIndex), ...
                        histories(1:rowIndex), settings);
                    rethrow(exception)
                end
            end

            saveCheckpoint( ...
                studyDirectory, rows(1:rowIndex), ...
                histories(1:rowIndex), settings);
        end
    end
end

summary = struct2table(rows);
writetable(summary, fullfile(studyDirectory, "run_summary.csv"));
aggregate = aggregateRuns(summary);
writetable(aggregate, fullfile(studyDirectory, "aggregate_summary.csv"));
paired = pairedDifferences(summary);
writetable(paired, fullfile(studyDirectory, "paired_differences.csv"));
save(fullfile(studyDirectory, "study_results.mat"), ...
    "summary", "aggregate", "paired", "histories", "settings", ...
    "manifest", "-v7");

plotHypervolumeHistories(histories, problemIds, profiles, ...
    settings.SequentialBudget, ...
    fullfile(studyDirectory, "fixed_hypervolume_history.png"));
plotAggregateMetrics(summary, problemIds, profiles, ...
    fullfile(studyDirectory, "aggregate_diagnostics.png"));
end

function settings = resolveSettings(overrides)
defaults = struct( ...
    "ProblemIds", [ ...
        "CF1_D10", "C2DTLZ2_D6_R02", "OSY", "MW7_D6"], ...
    "Replicates", 1:3, ...
    "SequentialBudget", 60, ...
    "ProbeCount", 65536, ...
    "OutputRoot", string(fullfile( ...
        fileparts(mfilename("fullpath")), "results")), ...
    "ContinueOnFailure", true);
validateattributes(overrides, {'struct'}, {'scalar'}, ...
    mfilename, "settings");
names = fieldnames(overrides);
settings = defaults;
for index = 1:numel(names)
    name = names{index};
    if ~isfield(defaults, name)
        error("cTSEMO:HighDimStudy:UnknownSetting", ...
            "Unknown study setting '%s'.", name);
    end
    settings.(name) = overrides.(name);
end

validateattributes(settings.ProblemIds, {'char', 'string'}, ...
    {'nonempty'}, mfilename, "settings.ProblemIds");
validateattributes(settings.Replicates, {'numeric'}, ...
    {'vector', 'integer', 'positive', 'finite'}, ...
    mfilename, "settings.Replicates");
validateattributes(settings.SequentialBudget, {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'}, ...
    mfilename, "settings.SequentialBudget");
validateattributes(settings.ProbeCount, {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'}, ...
    mfilename, "settings.ProbeCount");
validateattributes(settings.OutputRoot, {'char', 'string'}, ...
    {'scalartext'}, mfilename, "settings.OutputRoot");
if ~(islogical(settings.ContinueOnFailure) && ...
        isscalar(settings.ContinueOnFailure))
    error("cTSEMO:HighDimStudy:InvalidContinueOnFailure", ...
        "ContinueOnFailure must be a logical scalar.");
end
settings.ProblemIds = string(settings.ProblemIds);
settings.OutputRoot = string(settings.OutputRoot);
end

function count = initialCountForProblem(problemId)
switch string(problemId)
    case "CF1_D10"
        count = 30;
    otherwise
        count = 24;
end
end

function [row, history] = summarizeRun( ...
        row, result, problem, probeUnit, probeTruth, profile)
labels = logical(result.data.isFeasible);
nInitial = result.data.nInitial;
sequentialLabels = labels((nInitial + 1):end);
sources = reshape(string({result.iterations.selectionSource}), [], 1);
selectedPof = reshape(arrayfun(@(record) ...
    double(record.selected.pof), result.iterations), [], 1);

XUnit = normalizeToUnit( ...
    result.data.X, problem.lowerBound, problem.upperBound);
[pofModel, pofFit] = ctsemo.fitClippedBinaryPof( ...
    XUnit, labels, result.options);
pof = ctsemo.predictClippedBinaryPof(pofModel, probeUnit);
fieldMetrics = binaryFieldMetrics(probeTruth, pof);

[objectiveLower, objectiveUpper, referencePoint] = ...
    objectiveMetricDefinition(problem.id);
fixedHistory = fixedHypervolumeHistory( ...
    result.data.Y, labels, nInitial, ...
    objectiveLower, objectiveUpper, referencePoint);

row.TotalEvaluations = size(result.data.X, 1);
row.FinalFeasibleCount = nnz(labels);
row.SequentialFeasibleCount = nnz(sequentialLabels);
row.SequentialFeasibleRate = mean(sequentialLabels);
row.FirstFeasibleEvaluation = firstTrueIndex(labels);
row.PrimarySelections = nnz(sources == "primary");
row.ChallengerSelections = nnz(sources == "challenger");
row.FallbackSelections = nnz(sources == "fallback");
row.ChallengerFraction = row.ChallengerSelections ./ ...
    max(1, row.PrimarySelections + row.ChallengerSelections);
row.PrimarySelectedFeasibleRate = selectedSourceFeasibleRate( ...
    sources, sequentialLabels, "primary");
row.ChallengerSelectedFeasibleRate = selectedSourceFeasibleRate( ...
    sources, sequentialLabels, "challenger");
row.PrequentialBrier = mean( ...
    (selectedPof - double(sequentialLabels)) .^ 2);
row.FinalParetoCount = result.pareto.nPoints;
row.FinalFixedHypervolume = fixedHistory(end);
row.FixedHypervolumeAUC = ...
    trapz(0:(numel(fixedHistory) - 1), fixedHistory) ./ ...
    max(1, numel(fixedHistory) - 1);
row.PofAUC = fieldMetrics.AUC;
row.PofAveragePrecision = fieldMetrics.AveragePrecision;
row.PofBrier = fieldMetrics.Brier;
row.PofBalancedBrier = fieldMetrics.BalancedBrier;
row.PofECE10 = fieldMetrics.ECE10;
row.PofBalancedAccuracy = fieldMetrics.BalancedAccuracy;
row.PofFalsePositiveRate = fieldMetrics.FalsePositiveRate;
row.PofFalseNegativeRate = fieldMetrics.FalseNegativeRate;
row.PofFalseDiscoveryRate = fieldMetrics.FalseDiscoveryRate;
row.PofPredictedFeasibleRate = fieldMetrics.PredictedFeasibleRate;
row.PofAmbiguousRate = fieldMetrics.AmbiguousRate;
row.PofZeroMass = fieldMetrics.ZeroMass;
row.PofOneMass = fieldMetrics.OneMass;
row.PofBaseLength = pofModel.baseLength;
row.PofTrainingLengthMinimum = pofFit.trainingLengthMinimum;
row.PofTrainingLengthMaximum = pofFit.trainingLengthMaximum;
row.MeanPrimaryCandidatesScored = mean(arrayfun( ...
    @(record) record.primary.candidateCount, result.iterations));
row.MeanChallengerCandidatesScored = mean(arrayfun( ...
    @(record) record.challenger.candidateCount, result.iterations));
row.WallTimeSeconds = result.meta.wallTimeSeconds;
row.MeanAcquisitionSeconds = mean(arrayfun( ...
    @(record) record.timing.acquisitionSeconds, result.iterations));

history = emptyHistory();
history.ProblemId = string(problem.id);
history.Profile = profile;
history.Replicate = row.Replicate;
history.Hypervolume = fixedHistory;
end

function metrics = binaryFieldMetrics(truth, score)
truth = logical(truth(:));
score = min(1, max(0, double(score(:))));
predicted = score >= 0.5;
positive = truth;
negative = ~truth;
truePositive = nnz(predicted & positive);
falsePositive = nnz(predicted & negative);
falseNegative = nnz(~predicted & positive);
trueNegative = nnz(~predicted & negative);

metrics = struct();
metrics.AUC = rocAuc(truth, score);
metrics.AveragePrecision = averagePrecision(truth, score);
metrics.Brier = mean((score - double(truth)) .^ 2);
metrics.BalancedBrier = 0.5 .* ( ...
    mean((score(positive) - 1) .^ 2) + ...
    mean(score(negative) .^ 2));
metrics.ECE10 = expectedCalibrationError(truth, score, 10);
metrics.FalsePositiveRate = falsePositive ./ ...
    max(1, falsePositive + trueNegative);
metrics.FalseNegativeRate = falseNegative ./ ...
    max(1, falseNegative + truePositive);
metrics.FalseDiscoveryRate = falsePositive ./ ...
    max(1, falsePositive + truePositive);
metrics.BalancedAccuracy = 0.5 .* ( ...
    truePositive ./ max(1, truePositive + falseNegative) + ...
    trueNegative ./ max(1, trueNegative + falsePositive));
metrics.PredictedFeasibleRate = mean(predicted);
metrics.AmbiguousRate = mean(score > 1 ./ 3 & score < 2 ./ 3);
metrics.ZeroMass = mean(score == 0);
metrics.OneMass = mean(score == 1);
end

function value = rocAuc(truth, score)
positiveCount = nnz(truth);
negativeCount = nnz(~truth);
if positiveCount == 0 || negativeCount == 0
    value = NaN;
    return
end
[sortedScore, order] = sort(score, "ascend");
ranks = (1:numel(score)).';
startIndex = 1;
while startIndex <= numel(sortedScore)
    stopIndex = startIndex;
    while stopIndex < numel(sortedScore) && ...
            sortedScore(stopIndex + 1) == sortedScore(startIndex)
        stopIndex = stopIndex + 1;
    end
    ranks(startIndex:stopIndex) = 0.5 .* ...
        (startIndex + stopIndex);
    startIndex = stopIndex + 1;
end
unsortedRanks = zeros(size(ranks));
unsortedRanks(order) = ranks;
value = (sum(unsortedRanks(truth)) - ...
    positiveCount .* (positiveCount + 1) ./ 2) ./ ...
    (positiveCount .* negativeCount);
end

function value = averagePrecision(truth, score)
if ~any(truth)
    value = NaN;
    return
end
[sortedScore, order] = sort(score, "descend");
orderedTruth = truth(order);
truePositive = cumsum(orderedTruth);
groupEnd = [find(diff(sortedScore) ~= 0); numel(sortedScore)];
precision = truePositive(groupEnd) ./ groupEnd;
recall = truePositive(groupEnd) ./ nnz(truth);
value = sum(diff([0; recall]) .* precision);
end

function value = expectedCalibrationError(truth, score, binCount)
edges = linspace(0, 1, binCount + 1);
value = 0;
for binIndex = 1:binCount
    if binIndex < binCount
        inBin = score >= edges(binIndex) & ...
            score < edges(binIndex + 1);
    else
        inBin = score >= edges(binIndex) & ...
            score <= edges(binIndex + 1);
    end
    if any(inBin)
        value = value + mean(inBin) .* abs( ...
            mean(score(inBin)) - mean(truth(inBin)));
    end
end
end

function history = fixedHypervolumeHistory( ...
        Y, labels, nInitial, lower, upper, referencePoint)
sequentialCount = size(Y, 1) - nInitial;
history = zeros(sequentialCount + 1, 1);
for index = 0:sequentialCount
    prefix = 1:(nInitial + index);
    feasibleY = Y(prefix(labels(prefix)), :);
    if isempty(feasibleY)
        history(index + 1) = 0;
    else
        normalizedY = (feasibleY - lower) ./ (upper - lower);
        history(index + 1) = ctsemo.hypervolume2d( ...
            normalizedY, referencePoint);
    end
end
end

function [lower, upper, referencePoint] = ...
        objectiveMetricDefinition(problemId)
switch string(problemId)
    case "CF1_D10"
        lower = [0, 0];
        upper = [3, 3];
    case "C2DTLZ2_D6_R02"
        lower = [0, 0];
        upper = [2.25, 2.25];
    case "OSY"
        lower = [-1712, 2];
        upper = [0, 386];
    case "MW7_D6"
        lower = [0, 0];
        upper = [11, 11];
    otherwise
        error("cTSEMO:HighDimStudy:NoMetricReference", ...
            "No fixed objective scaling is registered for '%s'.", ...
            problemId);
end
referencePoint = [1.05, 1.05];
end

function index = firstTrueIndex(values)
index = find(values, 1, "first");
if isempty(index)
    index = NaN;
end
end

function rate = selectedSourceFeasibleRate(sources, labels, source)
selected = sources == source;
if any(selected)
    rate = mean(labels(selected));
else
    rate = NaN;
end
end

function normalized = normalizeToUnit(X, lower, upper)
normalized = (double(X) - lower) ./ (upper - lower);
end

