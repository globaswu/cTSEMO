function createDirectory(pathValue)
if ~isfolder(pathValue)
    [created, message] = mkdir(pathValue);
    if ~created
        error("cTSEMO:HighDimStudy:DirectoryCreationFailed", ...
            "Could not create '%s': %s", pathValue, message);
    end
end
end

function writeJson(pathValue, value)
fileId = fopen(pathValue, "w");
if fileId < 0
    error("cTSEMO:HighDimStudy:ManifestWriteFailed", ...
        "Could not open '%s' for writing.", pathValue);
end
cleanup = onCleanup(@() fclose(fileId));
fwrite(fileId, jsonencode(value), "char");
clear cleanup
end
