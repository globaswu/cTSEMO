function aggregate = aggregateRuns(summary)
completed = summary(summary.Status == "completed", :);
problemIds = unique(completed.ProblemId, "stable");
profiles = unique(completed.Profile, "stable");
rows = repmat(emptyAggregateRow(), ...
    numel(problemIds) .* numel(profiles), 1);
rowIndex = 0;
for problemIndex = 1:numel(problemIds)
    for profileIndex = 1:numel(profiles)
        selected = completed.ProblemId == problemIds(problemIndex) & ...
            completed.Profile == profiles(profileIndex);
        if ~any(selected)
            continue
        end
        rowIndex = rowIndex + 1;
        block = completed(selected, :);
        rows(rowIndex).ProblemId = problemIds(problemIndex);
        rows(rowIndex).Profile = profiles(profileIndex);
        rows(rowIndex).Replicates = height(block);
        rows(rowIndex).MeanFinalFixedHypervolume = ...
            mean(block.FinalFixedHypervolume, "omitnan");
        rows(rowIndex).MedianFinalFixedHypervolume = ...
            median(block.FinalFixedHypervolume, "omitnan");
        rows(rowIndex).MeanFixedHypervolumeAUC = ...
            mean(block.FixedHypervolumeAUC, "omitnan");
        rows(rowIndex).MeanSequentialFeasibleRate = ...
            mean(block.SequentialFeasibleRate, "omitnan");
        rows(rowIndex).MeanPofAUC = ...
            mean(block.PofAUC, "omitnan");
        rows(rowIndex).MeanPofAveragePrecision = ...
            mean(block.PofAveragePrecision, "omitnan");
        rows(rowIndex).MeanPofBrier = ...
            mean(block.PofBrier, "omitnan");
        rows(rowIndex).MeanPofBalancedAccuracy = ...
            mean(block.PofBalancedAccuracy, "omitnan");
        rows(rowIndex).MeanChallengerFraction = ...
            mean(block.ChallengerFraction, "omitnan");
        rows(rowIndex).MeanFallbackSelections = ...
            mean(block.FallbackSelections, "omitnan");
        rows(rowIndex).MeanWallTimeSeconds = ...
            mean(block.WallTimeSeconds, "omitnan");
        rows(rowIndex).MeanAcquisitionSeconds = ...
            mean(block.MeanAcquisitionSeconds, "omitnan");
    end
end
aggregate = struct2table(rows(1:rowIndex));
end

function paired = pairedDifferences(summary)
completed = summary(summary.Status == "completed", :);
problems = unique(completed.ProblemId, "stable");
replicates = unique(completed.Replicate, "stable");
rows = repmat(emptyPairedRow(), numel(problems) .* numel(replicates), 1);
rowIndex = 0;
for problemIndex = 1:numel(problems)
    for replicateIndex = 1:numel(replicates)
        common = completed.ProblemId == problems(problemIndex) & ...
            completed.Replicate == replicates(replicateIndex);
        legacy = completed(common & ...
            completed.Profile == "legacy_primary_filter", :);
        patched = completed(common & ...
            completed.Profile == "complete_pool", :);
        if height(legacy) ~= 1 || height(patched) ~= 1
            continue
        end
        rowIndex = rowIndex + 1;
        rows(rowIndex).ProblemId = problems(problemIndex);
        rows(rowIndex).Replicate = replicates(replicateIndex);
        rows(rowIndex).DeltaFinalFixedHypervolume = ...
            patched.FinalFixedHypervolume - ...
            legacy.FinalFixedHypervolume;
        rows(rowIndex).DeltaFixedHypervolumeAUC = ...
            patched.FixedHypervolumeAUC - ...
            legacy.FixedHypervolumeAUC;
        rows(rowIndex).DeltaSequentialFeasibleRate = ...
            patched.SequentialFeasibleRate - ...
            legacy.SequentialFeasibleRate;
        rows(rowIndex).DeltaPofAUC = ...
            patched.PofAUC - legacy.PofAUC;
        rows(rowIndex).DeltaPofBrier = ...
            patched.PofBrier - legacy.PofBrier;
        rows(rowIndex).DeltaChallengerFraction = ...
            patched.ChallengerFraction - ...
            legacy.ChallengerFraction;
        rows(rowIndex).DeltaFallbackSelections = ...
            patched.FallbackSelections - ...
            legacy.FallbackSelections;
        rows(rowIndex).DeltaWallTimeSeconds = ...
            patched.WallTimeSeconds - legacy.WallTimeSeconds;
    end
end
paired = struct2table(rows(1:rowIndex));
end

function plotHypervolumeHistories( ...
        histories, problemIds, profiles, budget, pathValue)
figureHandle = figure("Visible", "off", "Color", "white", ...
    "Position", [100, 100, 1200, 760]);
layout = tiledlayout(figureHandle, 2, 2, ...
    "TileSpacing", "compact", "Padding", "compact");
colors = [0.80, 0.25, 0.20; 0.15, 0.45, 0.75];
for problemIndex = 1:numel(problemIds)
    axisHandle = nexttile(layout);
    hold(axisHandle, "on");
    for profileIndex = 1:numel(profiles)
        selected = string({histories.ProblemId}) == ...
            problemIds(problemIndex) & ...
            string({histories.Profile}) == profiles(profileIndex);
        selectedHistories = histories(selected);
        if isempty(selectedHistories)
            continue
        end
        values = horzcat(selectedHistories.Hypervolume);
        plot(axisHandle, 0:budget, values, ...
            "Color", [colors(profileIndex, :), 0.22], ...
            "LineWidth", 0.8, "HandleVisibility", "off");
        plot(axisHandle, 0:budget, mean(values, 2), ...
            "Color", colors(profileIndex, :), ...
            "LineWidth", 2.2, ...
            "DisplayName", strrep(profiles(profileIndex), "_", " "));
    end
    title(axisHandle, strrep(problemIds(problemIndex), "_", " "));
    xlabel(axisHandle, "Sequential evaluations");
    ylabel(axisHandle, "Fixed normalized hypervolume");
    grid(axisHandle, "on");
    if problemIndex == 1
        legend(axisHandle, "Location", "best");
    end
end
title(layout, ...
    "Higher-dimensional cTSEMO: paired fixed-reference hypervolume");
exportgraphics(figureHandle, pathValue, "Resolution", 200);
close(figureHandle);
end

function plotAggregateMetrics(summary, problemIds, profiles, pathValue)
completed = summary(summary.Status == "completed", :);
metrics = [ ...
    "FinalFixedHypervolume", "PofAUC", ...
    "PofBrier", "ChallengerFraction"];
labels = [ ...
    "Final fixed hypervolume", "Final PoF AUC", ...
    "Final PoF Brier score", "Challenger selection fraction"];
figureHandle = figure("Visible", "off", "Color", "white", ...
    "Position", [100, 100, 1200, 760]);
layout = tiledlayout(figureHandle, 2, 2, ...
    "TileSpacing", "compact", "Padding", "compact");
colors = [0.80, 0.25, 0.20; 0.15, 0.45, 0.75];
for metricIndex = 1:numel(metrics)
    axisHandle = nexttile(layout);
    means = nan(numel(problemIds), numel(profiles));
    deviations = nan(size(means));
    for problemIndex = 1:numel(problemIds)
        for profileIndex = 1:numel(profiles)
            selected = completed.ProblemId == problemIds(problemIndex) & ...
                completed.Profile == profiles(profileIndex);
            values = completed.(metrics(metricIndex))(selected);
            means(problemIndex, profileIndex) = mean(values, "omitnan");
            deviations(problemIndex, profileIndex) = std(values, "omitnan");
        end
    end
    bars = bar(axisHandle, (1:numel(problemIds)).', ...
        means, "grouped");
    for profileIndex = 1:numel(profiles)
        bars(profileIndex).FaceColor = colors(profileIndex, :);
        x = bars(profileIndex).XEndPoints;
        hold(axisHandle, "on");
        errorbar(axisHandle, x, means(:, profileIndex), ...
            deviations(:, profileIndex), "k", ...
            "LineStyle", "none", "CapSize", 4);
    end
    axisHandle.XTick = 1:numel(problemIds);
    axisHandle.XTickLabel = strrep(problemIds, "_", " ");
    axisHandle.XTickLabelRotation = 18;
    ylabel(axisHandle, labels(metricIndex));
    grid(axisHandle, "on");
    if metricIndex == 1
        legend(axisHandle, strrep(profiles, "_", " "), ...
            "Location", "best");
    end
end
title(layout, ...
    "Higher-dimensional cTSEMO engineering-screen diagnostics");
exportgraphics(figureHandle, pathValue, "Resolution", 200);
close(figureHandle);
end

