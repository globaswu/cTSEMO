function [profile, runtimeOptions, portableOptions] = ...
        weldedBeamSensitivityProfile(profileId, outputDirectory)
%WELDEDBEAMSENSITIVITYPROFILE Build one fixed WB150 sensitivity profile.
%   This helper parses the exact option structures used by
%   runWeldedBeamProfileSensitivity without running the optimizer.

narginchk(1, 2);
if nargin < 2
    outputDirectory = "";
end
validateattributes(profileId, {'char', 'string'}, {'scalartext'}, ...
    mfilename, 'profileId');
validateattributes(outputDirectory, {'char', 'string'}, {'scalartext'}, ...
    mfilename, 'outputDirectory');

profileId = lower(string(profileId));
switch profileId
    case "shipped"
        profile = makeProfile("shipped", 1024, 512, 256);
    case "higher_compute"
        profile = makeProfile("higher_compute", 2048, 1024, 1000);
    otherwise
        error('cTSEMO:Sensitivity:UnknownProfile', ...
            'Unknown welded-beam sensitivity profile "%s".', profileId);
end

overrides = struct( ...
    'maxEvaluations', 130, ...
    'seed', 2026072506, ...
    'feasibility', struct('inputEncoding', 'feasibleIsOne'), ...
    'candidates', struct('primaryCount', ...
    profile.PrimaryCandidateCount), ...
    'objectiveGP', struct('nFeatures', ...
    profile.ObjectiveFeatureCount), ...
    'challengers', struct( ...
    'enabled', true, ...
    'count', profile.ChallengerCandidateCount), ...
    'logging', struct( ...
    'level', "summary", ...
    'directory', string(outputDirectory), ...
    'checkpoint', false, ...
    'saveEveryIteration', false));
runtimeOptions = cTSEMOOptions(overrides);
portableOptions = runtimeOptions;
portableOptions.logging.directory = "@PROFILE_ROOT@";
end

function profile = makeProfile(id, primaryCount, challengerCount, featureCount)
profile = struct( ...
    'Id', id, ...
    'PrimaryCandidateCount', primaryCount, ...
    'ChallengerCandidateCount', challengerCount, ...
    'ObjectiveFeatureCount', featureCount);
end
