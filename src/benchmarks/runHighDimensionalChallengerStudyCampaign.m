%RUNHIGHDIMENSIONALCHALLENGERSTUDYCAMPAIGN Execute the July 2026 screen.
% This script fixes the engineering-screen protocol used to compare the
% legacy primary-only Pareto filter with complete-pool scoring. The four
% mathematical benchmarks are cheap; the 96 sequential evaluations emulate
% a limited expensive-evaluation budget.

benchmarkRoot = fileparts(mfilename("fullpath"));
releaseRoot = fileparts(benchmarkRoot);
addpath(releaseRoot, benchmarkRoot);

campaignSettings = struct( ...
    "ProblemIds", [ ...
        "CF1_D10", "C2DTLZ2_D6_R02", "OSY", "MW7_D6"], ...
    "Replicates", 1:3, ...
    "SequentialBudget", 96, ...
    "ProbeCount", 65536, ...
    "OutputRoot", string(fullfile( ...
        benchmarkRoot, "results", ...
        "high_dimensional_gpmean_complete_pool_20260726")), ...
    "ContinueOnFailure", true);

[campaignSummary, campaignAggregate, campaignDirectory] = ...
    runHighDimensionalChallengerStudy(campaignSettings);
disp(campaignDirectory);
disp(campaignAggregate);
